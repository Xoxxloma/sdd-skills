#!/usr/bin/env bash
# Склейка частей в assemble.sh (предметная область — условная обсерватория). Части пишут один ключ
# по-разному (строка запроса, аргументы, хвост « — описание», слово между направлением и топиком, пометка
# в скобках, без бэктиков) и одну сущность двумя перечнями полей.
# Ждём: один блок на ключ, ключ по шаблону; один перечень полей (основа — блок с типами, новые имена —
# короткими строками), семантика `— ` обеих частей, одна строка `сущности:` без буллета, строка с отступом
# при своей строке, блок без дубля как есть. «Бизнес-правила» пишет голова: блок части отброшен, в описи —
# строки головы, а не сырьё частей. Запуск из любого места: bash run.sh — печатает ОК или дифф.
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$(mktemp -d)"; trap 'rm -rf "$OUT"' EXIT
bash "$HERE/../../../service-map-2.0/reference/assemble.sh" "$HERE/parts" 2 2026-10-19 "$OUT/card.md" "$OUT/opis.md" > "$OUT/log" || { cat "$OUT/log"; exit 1; }
grep -q '^отброшено: секция «Бизнес-правила» у частей 01' "$OUT/log" || { echo "нет строки «отброшено» для «Бизнес-правил»"; exit 1; }
diff "$HERE/expect.md" "$OUT/card.md" && diff "$HERE/expect.opis.md" "$OUT/opis.md" && echo "ОК"
