# ARS-703 — на события входа сервиса аутентификации, предмет НЕ пересекается с допусками.
# Меряется Шаг 4: #0 на двоих, третий назван отдельно, строка «своего БТ у #0 не будет».
# 2026-10-07 (PLAN-BR-SECTIONS D16): у эпика ARS-700 и у каждого ребёнка есть §4.3 «Бизнес-данные»; у детей — копия
# эпика со строкой «Унаследовано из эпика ARS-700». Унаследованный §4.3 — не признак общего источника для #0.
set -u
DEST="${1:?куда}"; HERE="$(cd "$(dirname "$0")" && pwd)"
rm -rf "$DEST"; mkdir -p "$DEST"; cp -r "$HERE/docs" "$DEST/docs"
echo "песочница: $DEST   файлов: $(find "$DEST" -type f | wc -l)"
