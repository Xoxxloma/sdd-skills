#!/usr/bin/env bash
# seed.sh — БТ со статусом «Требуются уточнения (2)» и двумя открытыми пунктами. Зов идёт
# с `--no-review`, поэтому приёмка не вызывается и гейт Шага 2Б обязан сработать по одному
# статусу: назвать оба пункта и задать ОДИН вопрос «поправить сейчас / идти как есть».
set -u
DEST="${1:?куда}"; HERE="$(cd "$(dirname "$0")" && pwd)"
rm -rf "$DEST"; mkdir -p "$DEST"; cp -r "$HERE/docs" "$DEST/docs"
echo "песочница: $DEST   файлов: $(find "$DEST" -type f | wc -l)"
