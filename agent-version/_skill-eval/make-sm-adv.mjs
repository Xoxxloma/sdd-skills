const S = ['list', 'create', 'update', 'remove', 'export', 'search', 'count', 'bulk']
const ep = (n, pre = '/api/v1/items', f = k => `\`${k}\``) =>
  Array.from({ length: n }, (_, i) => f(`${M[i % 4]} ${pre}/${S[i % 8]}${Math.floor(i / 8) ? '-' + Math.floor(i / 8) : ''}`))
const ENT = ['Order', 'Customer', 'Invoice', 'Payment', 'Shipment', 'Carrier', 'Warehouse', 'Slot', 'Tariff', 'Zone', 'Route', 'Driver', 'Vehicle', 'Contract', 'Claim', 'Refund', 'Audit', 'Session', 'Token', 'Role', 'Note', 'Tag', 'File', 'Batch', 'Lot', 'Bid', 'Offer', 'Quote', 'Lead', 'Deal']
const ent = (n, f = k => `\`${k}\``) => ENT.slice(0, n).map(f)
