const tasks = ['nightlyRecalc', 'purgeAudit', 'rotateKeys', 'syncTariffs'].map(k => `\`${k}\``)
const call = (n, f = (s, c) => `\`${s}\` · \`${c}\``) => Array.from({ length: n }, (_, i) => f('repairy-api', `${M[i % 4]} /auth/${S[i % 8]}${Math.floor(i / 8) ? '-' + Math.floor(i / 8) : ''}`))
const screens = n => Array.from({ length: n }, (_, i) => `\`/${S[i % 8]}${Math.floor(i / 8) ? '-' + Math.floor(i / 8) : ''}\``)

const block = (title, cls) => {
  const lines = [`## ${title}`]
  for (const [name, keys] of Object.entries(cls)) {
    lines.push(`${name} (${keys.length}):`)
    if (!keys.length) lines.push('  (секция пустой формой: `—` / `| — | | |`)')
    for (const k of keys) lines.push(`  ${k}`)
    lines.push('')
  }
  return lines.join('\n')
}
const withBody = (keys, counts) => keys.map((k, i) => `${k}   [строк «- » под заголовком: ${counts[i]}]`)

const write = (group, name, text) => {
  mkdirSync(join(iso, group), { recursive: true })
  writeFileSync(join(iso, group, `case-${name}.md`), text.trimEnd() + '\n')
}
const expectAll = {}
const add = (group, name, text, exp) => { write(group, name, text); (expectAll[group] ??= {})[name] = exp }

