// Изолированные группы (без инструментов, как SM-GATE/SM-GUARD): guard, mgate, promote, abort,
// pending, topup, keyed. Раннер — run-sm-adv-iso.sh, грейдер — grade-sm-adv-iso.mjs.
// Карточки-варианты режутся из fixtures/BR-REAL/services/ — прежние карточки для плеча rescan
// (SM_RESCAN_CARDS) и кандидат «прошлого прогона» для services/_pending/ (SM_ADV_PENDING).
//
// У каждого случая в expect.json: `want` — ожидаемый вердикт; `from` — откуда ожидание (инвариант);
// `design: true` — ожидание идёт от замысла, а текст скилла даёт другое (красный = текст победил);
// `exec: true` — проба проверяет исполнение формулы, не замысел.
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, 'fixtures', 'SM-ADV')
const iso = join(root, 'iso')

