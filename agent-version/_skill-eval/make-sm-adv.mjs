const perLine = (t, f) => t.split('\n').map(f).join('\n')
// nobackticks: заголовки блоков и первые две ячейки таблиц — без бэктиков
const stripKeys = t => perLine(t, l => {
  if (/^### /.test(l)) return l.replace(/`/g, '')
  if (/^\| /.test(l) && !/^\|\s*-{2,}/.test(l)) {
    const c = l.split('|'); for (let i = 1; i <= Math.min(2, c.length - 2); i++) c[i] = c[i].replace(/`/g, ''); return c.join('|')
  }
  return l
})
putCards('nobackticks', stripKeys(api), stripKeys(web))
// spaced: двойной пробел между глаголом и путём, хвостовой пробел у заголовка
const spaceKeys = t => perLine(t, l => /^### `(GET|POST|PUT|PATCH|DELETE) /.test(l) ? l.replace(/^### `(\w+) /, '### `$1  ') + ' ' : l)
putCards('spaced', spaceKeys(api), web)
// pending-seed: кандидат «прошлого прогона» — прежняя карточка без 40 блоков auth+projects, scanned в прошлом
const dropBlocks = (t, re) => {
  const out = []; let skip = false
  for (const l of t.split('\n')) {
    if (/^### /.test(l)) skip = re.test(l)
    else if (/^## /.test(l)) skip = false
    if (!skip) out.push(l)
  }
  return out.join('\n')
}
// auth.controller.ts (22) + projects.controller.ts (18): `/projects` без `:pid`-модулей (те живут в своих контроллерах)
