// 25 — новое значение; 26 — ближайшее по ту сторону. Дата вида 2026-10-26 или 26.10 числом 26 не считается.
const V25 = /(^|[^\d.,-])25(-?(я|ю|ая|ую|й|ой|и|ти))?([^\d]|$)/
const B26 = /(^|[^\d.,-])26(-?(я|ю|ая|ую|й|ой|и|ти))?(?![\d.]\d)([^\d]|$)/
/** Вопрос о границе в строке с «?». «Границы правки» (правило 6 скилла) — не граница порога. */
const RE_BOUND_W = /(^|[^\d.,-])26([^\d]|$)|включительн|ближайш[а-яё]*\s+(значени|числ)|по\s+ту\s+сторону|на\s+границе|граничн|сверх\s+лимит|превыш[а-яё]*\s+лимит|свыше\s+25|больше\s+25|после\s+25/i
/** Вопрос/гипотеза о ПРИМЕРЕ на границе порога (:339-344): «включительно», ближайшее значение по ту сторону, пример
 *  на границе, пункт с предметом «Граница». Слово «граница» в описании параметра («`minutes` — верхняя граница времени
 *  в пути», scx-cr-ver-q/run-1, run-2) и «на границе зоны» — не вопрос о границе порога. */
const RE_BOUND_Q = /включительн|ближайш[а-яё]*\s+(значени|числ|верси)|по\s+ту\s+сторону|(пример[а-яё]*|значени[а-яё]*|ровно|самой)\s+на\s+границе|на\s+границе\s+(порог|лимит)|граничн[а-яё]*\s+(значени|случа|пример)|порогов[а-яё]*\s+значени|(где|какая|какой)\s+(проходит\s+)?границ|границ[а-яё]*\s+(порог|лимит)|^\s*(\d+[.)]\s*|[-*•]\s*)?\**\s*границ[аы]([^а-яё]|$)/im
/** «Границы правки» (правило 6 скилла, :38-41) и «границы задачи» — объём, а не граница порога. */
const RE_SCOPE_EDGE = /границ[а-яё]*\s+(правк|задач|изменени|объ[её]м)/i
const RE_REFUSE = /отклон|отказ|не\s+(проход|принима|прикреп|сохраня)|нельзя|блокир/i
/** Пример на границе числом: в строке есть N и N+1 (версии «v1», «v2» не в счёт) и слово отказа — «25 принимается, 26-е
 *  отклоняется» (живая форма cr-lim-q, 2026-10-26). */
export function numericEdge (line) {
  const ns = [...line.matchAll(/(^|[^\dvVвВ.,])(\d{1,6})(?![\d.,]\d)/g)].map((x) => Number(x[2]))
  return RE_REFUSE.test(line) && ns.some((n) => ns.includes(n + 1))
}
const RE_VERDICT_PRAVKA = /(это|—|:)\s*(мелкая\s+)?правка|мелкая правка|одна поставка|один деливербл/i
const RE_ASKS_KEY = /(укажите|назовите|пришлите|сообщите|дайте|нужен|требуется|не передан|не указан)[^.\n]{0,40}ключ|ключ[^.\n]{0,40}(не передан|не указан|❓)/i
const RE_PHANTOM = /(записал|записан|создал|создан|сохранил|сохранён|положил)[^\n]{0,80}change_request\.md|change_request\.md[^\n]{0,40}(записан|создан|сохранён|готов)/i

/** Тело раздела `## <заголовок>` до следующего `## `. */
function named (text, re) {
  const lines = text.split('\n')
  const i = lines.findIndex((l) => /^## /.test(l) && re.test(l))
  if (i < 0) return null
  const rest = lines.slice(i + 1)
  const j = rest.findIndex((l) => /^## /.test(l))
  return (j < 0 ? rest : rest.slice(0, j)).join('\n')
}
/** Текст без раздела `## <заголовок>` (заголовок и тело). */
function without (text, re) {
  const lines = text.split('\n')
  const i = lines.findIndex((l) => /^## /.test(l) && re.test(l))
  if (i < 0) return text
  const j = lines.slice(i + 1).findIndex((l) => /^## /.test(l))
  return lines.slice(0, i).concat(j < 0 ? [] : lines.slice(i + 1 + j)).join('\n')
}

/** Строка хендоффа «Открытые пункты: …» / «Открытый пункт: …» (change-request-doc/SKILL.md:310) и пункты списка сразу
 *  под ней — как набор строк ответа. */
function handoffOpen (answer) {
  const out = new Set()
  const lines = (answer || '').split('\n')
  for (let i = 0; i < lines.length; i++) {
    if (!/^\s*\**Открыт(ые|ый)\s+пункт[а-яё]*\**\s*:/i.test(lines[i])) continue
    out.add(lines[i])
    for (let j = i + 1; j < lines.length && /^\s*[-*•]\s+/.test(lines[j]); j++) out.add(lines[j])
  }
  return out
}

/** Строки ответа с вопросом, кроме финального «Годится?» хендоффа (у него нет предмета). */
function questionLines (answer) {
  return (answer || '').split('\n').filter((l) => l.includes('?') && !/^\s*\**Годится\?\**\s*$/.test(l))
}

export function grade (kase, answer, file) {
  const c = CASES[kase]
  const m = {}
  if (c.kind === 'w') {
    m['файл записан этим ходом'] = !!file
    // «Открытые вопросы» — не FR и не поведение: «в FR-1 не включено» там не спасает FR без 25 и не краснит 26.
    const behavior = file ? without(file, /Открытые вопросы/) : ''
    const fr = behavior.split('\n').filter((l) => /FR-\d/.test(l)).join('\n')
    m['FR-* несут 25'] = V25.test(fr)
    // 26 в «Открытых вопросах» — неизвестное, записанное как TBD (решение владельца, README), а не поведение. Красный —
    // 26 в FR, критерии и любом другом разделе, где файл записывает поведение.
    const open = file ? (named(file, /Открытые вопросы/) ?? '') : ''
    m['26 не записана как подтверждённое поведение (вне «Открытых вопросов»)'] = !!file && !B26.test(behavior)
    m._openBound = !!file && (RE_BOUND_W.test(open.replace(/Не осталось\.?/g, '')) || /сверх\s+25/i.test(open))
    // Строка хендоффа «Открытые пункты: … — ответите?» обязательна при открытых пунктах (:310). Пересказывает она
    // записанный в файле открытый вопрос о границе — это не переспрос. Переспрос — вопрос о границе вне неё.
    const recap = m._openBound ? handoffOpen(answer) : new Set()
    const qs = questionLines(answer).filter((l) => !recap.has(l) && RE_BOUND_W.test(l) && !RE_SCOPE_EDGE.test(l))
    m['граница не переспрошена в ответе'] = qs.length === 0
    m._q = qs
    m._status = file ? ((file.match(/Статус готовности:\*{0,2}\s*([^\n]+)/) || [])[1] || '?').trim() : '—'
    m._fr = fr.split('\n').filter(Boolean).slice(0, 2)
  } else {
    m['файла нет'] = !file
    m['вердикт «правка» назван'] = RE_VERDICT_PRAVKA.test(answer || '')
    m['ключ не переспрошен'] = !RE_ASKS_KEY.test(answer || '')
    const qs = questionLines(answer).filter((l) => (RE_BOUND_Q.test(l) || numericEdge(l)) && !RE_SCOPE_EDGE.test(l))
    m['нет вопроса о границе'] = qs.length === 0
    m._q = qs
    m._phantom = !file && RE_PHANTOM.test(answer || '')
  }
  return m
}

const bad = (m) => Object.entries(m).filter(([k, v]) => !k.startsWith('_') && !v).map(([k]) => k)

