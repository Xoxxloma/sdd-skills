function main () {
  if (process.argv.includes('--selftest')) process.exit(selftest() ? 1 : 0)
  const arg = process.argv[2]
  const kase = (process.argv.find((a) => a.startsWith('--case=')) || '').slice(7)
  if (!arg || !existsSync(arg) || !CASES[kase]) { console.error('usage: node grade-scx-cr.mjs <каталог плеча> --case=nob|own|api|ver'); process.exit(1) }
  const runs = readdirSync(arg).filter((n) => /^run-\d+$/.test(n) && statSync(join(arg, n)).isDirectory()).sort()
  console.log(`\nпроба scx-cr-${kase}, ${arg}`)
  let measured = 0; let green = 0; let openBound = 0
  const tot = {}
  for (const n of runs) {
    const dir = join(arg, n)
    const t1 = turn(dir, 1)
    if (existsSync(join(dir, '_escaped.txt')) || apiFailed(dir, [t1.answer])) { console.log(`  ${n}: НЕ ИЗМЕРЕНО`); continue }
    measured++
    const file = read(join(dir, 'coddoc', CASES[kase].key, 'change_request.md'))
    const m = grade(kase, t1.answer, file)
    const b = bad(m)
    if (!b.length) green++
    for (const k of b) tot[k] = (tot[k] || 0) + 1
    const extra = CASES[kase].kind === 'w' ? ` · статус: ${m._status} · граница в «Открытых вопросах» (справка): ${m._openBound ? 'да' : 'нет'}` : (m._phantom ? ' · ФАНТОМ: файл назван, на диске нет' : '')
    if (m._openBound) openBound++
    console.log(`  ${n}: ${b.length ? 'красный' : 'зелёный'}${extra}${b.length ? '  ✗ ' + b.join(' · ') : ''}`)
    for (const l of (m._fr || [])) console.log(`        FR: ${l.replace(/[*|#>]/g, '').trim().slice(0, 140)}`)
    for (const l of m._q.slice(0, 3)) console.log(`        ? ${l.replace(/[*|#>]/g, '').trim().slice(0, 140)}`)
  }
  for (const [k, v] of Object.entries(tot)) console.log(`  ${v}/${measured}\t${k}`)
  if (CASES[kase].kind === 'w') console.log(`  ${openBound}/${measured}\tпункт о границе в «Открытых вопросах» (справка, в зелёное не входит)`)
  console.log(`\n  ${green}/${measured}\tзелёных  ← КРИТЕРИЙ\n`)
}
