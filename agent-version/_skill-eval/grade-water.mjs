// grade-water.mjs — счётчик ВОДЫ в речи скилла к человеку. Работает на любом плече.
//
//   node grade-water.mjs <папка-плеча>
//   node grade-water.mjs --selftest
//
// ЧТО МЕРЯЕТСЯ. Текст `answer.md` — вопросы и варианты, которые видит аналитик. Здесь это
// законно: предмет замера и есть речь агента. Файлы на диске грейдят профильные грейдеры
// (`grade-bg.mjs`, `grade-ts.mjs`, `grade-br-open.mjs`), и этот счётчик их не заменяет.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВРЕЗКА. Классы одни и те же для `business-requirements-doc`,
// `bug-report-doc` и `technical-spec-doc` — блок правил в этих скиллах унифицирован. Врезка
// в три грейдера означала бы три копии списка, которые разъедутся на первой же правке.
//
// ЧЕГО ЗДЕСЬ НЕТ. Хвоста «что-то ещё»: он не нейрослоп, а нарушение уже написанного правила
// про варианты ответа («другое», «опишу в поле ввода» вариантом не бывают), и цена у него
// есть только в форме с кнопками — слот из 2–4 потрачен впустую. Стенд гоняет прозу, где
// хвост не отнимает у человека ничего, поэтому в счётчик воды он не входит: иначе число
// смешивало бы нейрослоп с нарушением чужого правила.
//
// Классы подтверждены разбором корпуса 2026-08-26 (прогоны `br-open` круга 2026-08-25).
// Границы слова — `(?!\p{L})` и флаг `u`: `\b` в JS знает только ASCII и после кириллицы
// не срабатывает никогда, ошибка тихая.
import { readdirSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const RE_API_FAILURE = /API Error|Request timed out|rate limit|overloaded_error/i

const RE_WATER = [
  // «Бриф минимален и расплывчат», «это очень широко» — оценка слов человека вслух.
  { label: 'оценка его слов', re: /(очень\s+широк|слишком\s+общ|расплывчат|нужда\p{L}*\s+в\s+конкретик|это\s+понятно,?\s+но|эмоциональн\p{L}*\s+запрос)/iu },
  // «нужна система ИЛИ приложение», «инструмент ИЛИ механизм» — предмет не назван.
  { label: 'синонимы вместо предмета', re: /(?<!\p{L})(систем|приложени|инструмент|механизм|решени|платформ|сервис|функци)\p{L}*\s+или\s+(систем|приложени|инструмент|механизм|решени|платформ|сервис|функци)/iu },
  // «поможет отследить и организовать» вместо «показывает срок в карточке».
  { label: 'промо-глагол', re: /(?<!\p{L})(помож(ет|ут)|позвол(ит|ят|яет)|упрост(ит|ят|ить)|облегч(ит|ат|ить)|обеспеч(ит|ат|ить)|улучш(ит|ат|ить))(?!\p{L})/iu },
  // «собрать ключевую информацию и легко её выгружать». Служебная подпись хода («ключевой
  // вопрос», «важный шаг») эпитетом НЕ считается — украшается предмет, а не твоя реплика.
  { label: 'оценочный эпитет', re: /(?<!\p{L})(ключев\p{L}*|эффективн\p{L}*|оптимальн\p{L}*|комплексн\p{L}*|бесшовн\p{L}*|полноценн\p{L}*|удобн\p{L}*)(?!\p{L})(?!\s+(вопрос|момент|шаг|пункт|блокер|гейт))|легко\s+(её|его|их|это)/iu },
  // «что вас больнее всего», «наболело».
  { label: 'псевдо-эмпатия', re: /(?<!\p{L})(больнее\s+всего|наболе\p{L}*|мучает)(?!\p{L})/iu },
  // «по практике», «как правило» — опора на источник, которого нет.
  { label: 'ссылка в никуда', re: /(?<!\p{L})(обычно\s+(это\s+)?дела(ют|ется)|по\s+практике|как\s+правило|в\s+большинстве\s+случаев)(?!\p{L})/iu },
]

export function gradeAnswer(text) {
  return { water: RE_WATER.filter((w) => w.re.test(text)).map((w) => w.label) }
}

// ─── Самопроверка на дословных строках прогонов ────────────────────────────────────────────
const R05_SYN = `По вашему описанию понимаю так: нужна система или приложение, которое поможет отследить и организовать договоры подрядчиков. Верно?`
const R05_EMP = `Что именно вас сейчас больнее всего — найти конкретный договор, отследить сроки?`
const R08_EPI = `Реестр данных по договорам — вы хотите собрать в одном месте ключевую информацию из всех договоров и легко её выгружать для отчётов?`
const R06_JUD = `«Навести порядок» — это понятно, но что конкретно должно измениться или появиться?`
const RS_REF = `Читается ли одним сканом? По практике service-map — порог примерно 500 файлов.`
const CLEAN = `Укажите ключ задачи SMSEC-1234. Понял так: договоры лежат в разных местах, главная боль — не пропустить срок. Верно?`
const LEDGER = `**Ключевой вопрос — Gate 0 (обязательный блокер):** укажите ключ задачи.`
const TAIL = `Реестр подрядчиков, автоматизация уведомлений, что-то ещё?`

function selftest() {
  const checks = [
    ['run-05: «система или приложение» поймано', gradeAnswer(R05_SYN).water.includes('синонимы вместо предмета')],
    ['run-05: «поможет отследить» поймано', gradeAnswer(R05_SYN).water.includes('промо-глагол')],
    ['run-05: «больнее всего» поймано', gradeAnswer(R05_EMP).water.includes('псевдо-эмпатия')],
    ['run-08: «ключевую информацию» поймано', gradeAnswer(R08_EPI).water.includes('оценочный эпитет')],
    ['run-06: «это понятно, но» поймано', gradeAnswer(R06_JUD).water.includes('оценка его слов')],
    ['rs: «по практике» поймано', gradeAnswer(RS_REF).water.includes('ссылка в никуда')],
    ['ЛОВУШКА: чистый вопрос водой не считается', gradeAnswer(CLEAN).water.length === 0],
    ['ЛОВУШКА: «Ключевой вопрос» эпитетом не считается', !gradeAnswer(LEDGER).water.includes('оценочный эпитет')],
    ['ЛОВУШКА: хвост «что-то ещё» водой НЕ считается', gradeAnswer(TAIL).water.length === 0],
  ]
  let bad = 0
  for (const [label, ok] of checks) { if (!ok) bad++; console.log(`  ${ok ? '✔' : '✘'} ${label}`) }
  console.log(bad ? `\nСАМОПРОВЕРКА ПРОВАЛЕНА: ${bad}` : '\nсамопроверка пройдена')
  process.exit(bad ? 1 : 0)
}

// ─── CLI ───────────────────────────────────────────────────────────────────────────────────
const argv = process.argv.slice(2)
if (argv.includes('--selftest')) selftest()

const root = argv[0]
if (!root) { console.error('нужен путь к папке плеча (или --selftest)'); process.exit(1) }

const rows = readdirSync(root, { withFileTypes: true })
  .filter((e) => e.isDirectory() && /^run-\d+$/.test(e.name))
  .map((e) => e.name).sort()
  .map((name) => {
    const ans = join(root, name, 'answer.md')
    if (!existsSync(ans)) return { name, measured: false, why: 'нет answer.md' }
    const text = readFileSync(ans, 'utf8')
    if (RE_API_FAILURE.test(text)) return { name, measured: false, why: 'отказ API' }
    return { name, measured: true, ...gradeAnswer(text) }
  })

const measured = rows.filter((r) => r.measured)
console.log(`плечо: ${root}`)
console.log(`измерено: ${measured.length} из ${rows.length}` +
  (measured.length < rows.length ? `  (не измерено: ${rows.filter((r) => !r.measured).map((r) => `${r.name} — ${r.why}`).join(', ')})` : ''))
for (const r of measured) console.log(`  ${r.name}: ${r.water.length ? '\x1b[33mвода: ' + r.water.join(', ') + '\x1b[0m' : 'чисто'}`)

const wet = measured.filter((r) => r.water.length)
console.log(`\nВОДА: ${wet.length}/${measured.length}` +
  (measured.length ? ` (${Math.round((wet.length / measured.length) * 100)}%)` : ''))
if (wet.length) {
  const byClass = {}
  for (const r of wet) for (const w of r.water) byClass[w] = (byClass[w] || 0) + 1
  for (const [k, v] of Object.entries(byClass).sort((a, b) => b[1] - a[1])) console.log(`  ${String(v).padStart(3)}  ${k}`)
}
