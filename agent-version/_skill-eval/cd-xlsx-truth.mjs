// cd-xlsx-truth.mjs — истинное содержимое листа фикстуры CD-XLSX.
//
// Один источник на двоих: `make-cd-xlsx.mjs` собирает из него сам `.xlsx`, `grade-cdoc.mjs`
// сверяет с ним каждую ячейку перенесённой таблицы. Разъехаться им негде — правится этот файл,
// потом пересобирается фикстура.
//
// ЛЕЖИТ ВНЕ ФИКСТУРЫ НАМЕРЕННО. Раннер засевает песочницу всей папкой фикстуры (кроме `README.md`,
// `*-prompt.txt` и `_manifest.txt`), поэтому эталон, положенный рядом с `.xlsx`, приехал бы прогону
// готовой таблицей — и проба «извлёк ли он данные из контейнера» отвечала бы «да» сама себе.
//
// ── Почему лист именно такой ────────────────────────────────────────────────────────────────
// Первая редакция фикстуры (2026-08-16) держала лист 4×3, и на нём распаковка НЕ ломалась:
// 5 прогонов из 6 собрали таблицу вручную и не ошиблись ни в одной ячейке. Проба мерила
// дисциплину («удержался ли от записи»), а не то, ради чего заводилась.
//
// Здесь 60 строк и три ловушки сопоставления, каждая — на своё место, где рука может дрогнуть:
//
// 1. **Соплатёж 0…25 численно попадает в диапазон индексов словаря** (уникальных строк ~83).
//    В сетке `<c r="E7"><v>15</v></c>` — это ЧИСЛО 15, а `<c r="C7" t="s"><v>15</v></c>` —
//    пятнадцатая строка словаря. Различает их только атрибут `t="s"`, и ничто больше.
// 2. **Названия программ повторяются** по 15 раз каждое: в словаре они лежат по одному разу, и
//    шестьдесят ячеек ссылаются на четыре индекса. Сдвиг на единицу переставляет программу во
//    всех строках сразу — таблица остаётся правдоподобной.
// 3. **Порядок словаря не совпадает с порядком листа**: строки попадают в него по первому
//    появлению, поэтому «читать словарь сверху вниз параллельно строкам» даёт неверный ответ.

/** Услуги: имя и базовый лимит, от которого считаются лимиты программ. */
const SERVICES = [
  ['Приём терапевта', 2400],
  ['Приём узкого специалиста', 3150],
  ['УЗИ органов брюшной полости', 4870],
  ['МРТ одной области', 11600],
  ['КТ одной области', 9340],
  ['Лабораторная панель «биохимия»', 5280],
  ['Вызов врача на дом', 6100],
  ['Физиотерапия, курс', 7450],
  ['Стоматология: лечение кариеса', 8900],
  ['Стоматология: гигиена', 4200],
  ['Экстренная госпитализация, сутки', 24700],
  ['Плановая госпитализация, сутки', 18300],
  ['Вакцинация сезонная', 1950],
  ['Ведение беременности, месяц', 15400],
  ['Реабилитация после травмы, курс', 21800],
]

/** Программы: имя, множитель лимита (в сотых) и соплатёж в процентах. */
const PROGRAMS = [
  ['ДМС-Базовый', 100, 20],
  ['ДМС-Расширенный', 175, 10],
  ['ДМС-Стоматология', 130, 25],
  ['ДМС-Семейный', 240, 0],
]

/**
 * Строки листа: `[код, услуга, программа, лимит, соплатёж]`.
 *
 * Коды идут не подряд (шаг 7 по кольцу) — соседний код нельзя достроить из предыдущего, и
 * пропущенная строка сразу видна. Лимит некруглый по построению: базовый множится на сотые доли.
 */
export const ROWS = SERVICES.flatMap(([service, base], i) =>
  PROGRAMS.map(([program, mult, share], j) => {
    const n = i * PROGRAMS.length + j
    const code = `MED-${1000 + ((n * 7) % 60) + 1}`
    return [code, service, program, String(Math.round((base * mult) / 100)), String(share)]
  }))

export const HEADER = ['Код', 'Услуга', 'Программа', 'Лимит, ₽', 'Соплатёж, %']

/** Уникальные тексты в порядке первого появления — ровно так их складывает Excel. */
export function sharedStrings () {
  const seen = new Map()
  const push = (s) => { if (!seen.has(s)) seen.set(s, seen.size) }
  HEADER.forEach(push)
  for (const [code, service, program] of ROWS) { push(code); push(service); push(program) }
  return [...seen.keys()]
}

/** Числовые колонки листа (индексы в строке) — они пишутся без `t="s"`. */
export const NUMERIC_COLS = [3, 4]
