#!/usr/bin/env bash
# make-sm86-prompt.sh <SKILL.md> <card.template.md> <repo.md> [сервис] [имена-манифеста] > prompt.md
#
# Собирает промпт тира A (роль сканирующего субагента) для пробы SM-86.
#
# ПОЧЕМУ ГЕНЕРАТОР, А НЕ ФАЙЛ. Прежние промпты тира A (`runs/2026-07-30-fork/stand/`) держали
# бриф Шага 3 ДОСЛОВНОЙ КОПИЕЙ внутри себя. Правка скилла до субагента после этого не доезжает
# вовсе, и плечо «после правки» мерит прежний текст. Здесь бриф вырезается из указанного
# SKILL.md на каждый вызов: плечо `before` собирается из снимка, плечо `after` — из живого файла.
#
# Заголовок фикстуры (её README с точными числами инвентаря) в промпт НЕ идёт: он называет ответ.
# Содержимое берётся от первого блока «## `путь`» до «## Что здесь проверяется».
set -eu
SKILL="$1"; TMPL="$2"; REPO="$3"
SVC="${4:-/work/shipping-api}"
NAMES="${5:-shipping, carrier-registry, warehouse-web}"

FROM=$(grep -n '^\*\*Сначала опись, потом карточка' "$SKILL" | head -1 | cut -d: -f1)
TO=$(grep -n '^### Шаг 4' "$SKILL" | head -1 | cut -d: -f1)
[ -n "$FROM" ] && [ -n "$TO" ] || { echo "не нашёл границы брифа в $SKILL" >&2; exit 1; }

cat <<EOF
Ты — сканирующий субагент. Тебя запустил ведущий агент скилла \`service-map\` и передал всё, что
ниже. По диску ты ходишь только за формой карточки (путь ниже); других файлов не читаешь,
субагентов не запускаешь.

**Сервис:** \`$SVC\`, тип \`backend\`.
**Имена всех сервисов из манифеста:** $NAMES
**Прежней карточки нет.**

## Форма карточки

Прочитай целиком файл \`$TMPL\` — там форма карточки, ветвление секций по типу, ключи и правила
содержания. Ответ начни строкой \`шаблон прочитан, тип: backend\`.

## Три правила, которые важнее процедуры

**1. Не выводится из кода — пиши \`не определено\`.** Догадка, записанная как факт, через неделю
вернётся аналитику в виде «в \`services/auth.md\` описано, что…» и будет неотличима от правды.

**2. Ты только читаешь чужие репозитории.** Ни одного изменения в папке сервиса.

**3. Секреты не копируются.** Имя переменной и файл — да, значение — никогда.

## Порядок работы

EOF

sed -n "${FROM},$((TO - 1))p" "$SKILL"

cat <<EOF

## Две секции, которые ты не заполняешь

- «Заметки команды» не выводи вообще — их вставляет ведущий агент из манифеста.
- «Кто меня потребляет» выведи ПУСТОЙ ФОРМОЙ: заголовок и строку \`| — | | |\`.

## Что вернуть

Опись и текст карточки, и ничего больше, начав ответ строкой \`шаблон прочитан, тип: backend\`.
Файлов сервиса ты не пишешь.

---

# СОДЕРЖИМОЕ РЕПОЗИТОРИЯ \`$SVC\`

EOF

awk '/^## `/{f=1} /^## Что здесь проверяется/{exit} f' "$REPO"
