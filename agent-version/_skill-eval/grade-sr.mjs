/**
 * Секция блокеров: от заголовка «БЛОКЕРЫ» до «ЖЕЛАТЕЛЬНО» или до конца. Нужна, потому что
 * упоминание INT-3 в «желательно» или в счётной строке нарушением НЕ является — запрещено
 * требовать у чужой карточки контракт, а не называть её вовсе.
 */
function blockerSection (text) {
  // ЗАГОЛОВОК, А НЕ ЛЮБОЕ УПОМИНАНИЕ. Первая редакция искала `/БЛОКЕР/i` где угодно, и на
  // прогоне `sr-yellow/run-07` (2026-08-17) поймала строку рабочих заметок «INT-3 потеря ответа:
  // видел только бэк — один блокер»: дальше грейдер объявил её блокером на 🟡-карточке, хотя дыра
  // там про НАШУ обработку потерянного ответа и назвать её законно. Заголовок стоит один в
  // строке, поэтому от прозы отличается concretely: начало строки и конец строки рядом.
  // Хвост слова — `[^\s:*#>]*`, а НЕ `\w*`: в JS `\w` это `[A-Za-z0-9_]`, кириллицу он не берёт,
  // и «БЛОКЕРЫ» заголовком не признавалось. Та же ловушка, что `\Z` из шапки `grade-rv.mjs`.
  // Хвост — `[^\n]{0,30}$`, потому что заголовок часто несёт приписку: «ЖЕЛАТЕЛЬНО (топ-5)»,
  // «Блокеры (сортировка по цене):». Слишком строгий конец секции хуже слишком строгого начала:
  // не найдя закрывающего заголовка, счётчик проглатывал весь остаток документа вместе со
  // счётными строками и давал 30 блокеров на 🟡 вместо одного.
  const from = text.search(/^[\s*#>]*БЛОКЕР[^\n]{0,30}$/mi)
  if (from < 0) return ''
  const rest = text.slice(from)
  const to = rest.search(/^[\s*#>]*ЖЕЛАТЕЛ[^\n]{0,30}$/mi)
  return to < 0 ? rest : rest.slice(0, to)
}

