//
//   node grade-sr.mjs <каталог с песочницами> [--probe=gap]
//   node grade-sr.mjs --selftest
//
// ЧТО МЕРЯЕТСЯ. Фикстура `SR-GAP` — спека, у которой все рубрики шаблона заполнены честно и
