#!/usr/bin/env bash
# run-sm-mark.sh <SKILL.md> <папка-раунда> [N] — изолированная проба маркерного гейта под разведчика
# (фикстура SM-MARK, service-map-2.0, критерий А-2 плана PLAN-AUTOSPLIT).
# Из УКАЗАННОГО SKILL.md по якорям вырезаются: Шаг 3.0–3.1 (от «#### 3.0 Разведчик» до «#### 3.2 Запуск»)
# и маркерный гейт Шага 4 (от «**Второе — маркерный гейт» до «**Три правила обхода», первые после «### Шаг 4»).
# Прогон без инструментов получает их и один случай; последняя строка ответа — `МАРКЕРЫ: ПРОЙДЕН` либо
# `МАРКЕРЫ: ДОБОР`, строки отчёта — с `ОТЧЁТ:`. Грейдит `grade-sm-mark.mjs <раунд>/sm-mark`.
# SM_MARK_ONLY="ferry-contract-153-over-14" — гонять только названные случаи; SM_FIX, SM_OUT, SM_MODEL — как у run-sm-ent.sh.
set -u
SKILL="${1:?путь к SKILL.md}"; ROUND="${2:?папка раунда}"; N="${3:-3}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; FIX="${SM_FIX:-$HERE/fixtures/SM-MARK}"; OUT="$ROUND/${SM_OUT:-sm-mark}"
MODEL="${SM_MODEL:-sonnet}"
[ -f "$SKILL" ] || { echo "нет файла $SKILL" >&2; exit 1; }
ln() { grep -n -m1 -- "$1" "$SKILL" | cut -d: -f1; }
after() { grep -n -- "$2" "$SKILL" | awk -F: -v s="$1" '$1>s{print $1; exit}'; }
need() { [ -n "$2" ] || { echo "не нашёл якорь «$1» в $SKILL" >&2; exit 1; }; }
R1=$(ln '^#### 3\.0 Разведчик'); need '#### 3.0 Разведчик' "$R1"
R15=$(ln '^#### 3\.1 Маркерный счёт'); need '#### 3.1 Маркерный счёт' "$R15"
R2=$(ln '^#### 3\.2 Запуск'); need '#### 3.2 Запуск' "$R2"
S4=$(ln '^### Шаг 4'); need '### Шаг 4' "$S4"
A1=$(after "$S4" '^\*\*Второе — маркерный гейт'); need '**Второе — маркерный гейт (после ### Шаг 4)' "$A1"
A2=$(after "$A1" '^\*\*Три правила обхода'); need '**Три правила обхода (после маркерного гейта)' "$A2"
[ "$R1" -lt "$R15" ] && [ "$R15" -lt "$R2" ] || { echo "якоря 3.0/3.1/3.2 не по порядку: $R1 $R15 $R2" >&2; exit 1; }
mkdir -p "$OUT"; cp "$SKILL" "$OUT/_skill-snapshot.md"
printf 'модель: %s\nпрогонов на случай: %s\nякоря: 3.0–3.1 %s–%s, маркерный гейт %s–%s\n' "$MODEL" "$N" "$R1" "$R2" "$A1" "$A2" > "$OUT/_settings.txt"
# детектор узкого маркера по плану — «больше чем вдвое»; нет этих слов в вырезке — правило, возможно, живёт вне якорей
if ! { sed -n "${R1},$((R2-1))p" "$SKILL"; sed -n "${A1},$((A2-1))p" "$SKILL"; } | grep -q 'вдвое'; then
  echo "ВНИМАНИЕ: в вырезанном тексте нет «вдвое» — детектор узкого маркера может лежать вне якорей; случаи (б) и (е) тогда меряют стенд" | tee -a "$OUT/_settings.txt" >&2
fi
for c in "$FIX"/case-*.md; do
  v="$(basename "$c" .md)"; v="${v#case-}"
  if [ -n "${SM_MARK_ONLY:-}" ]; then case " $SM_MARK_ONLY " in *" $v "*) ;; *) continue ;; esac; fi
  mkdir -p "$OUT/$v"
  {
    echo 'Ты — ведущий агент скилла `service-map`. Ниже из твоего скилла дословно: Шаг 3.0–3.1 (разведчик и маркерный счёт) и маркерный гейт Шага 4. Затем — данные по одному сервису на Шаге 4: что вернул разведчик, сколько совпадений дал твой греп по каждой его строке, и итоги описи, которую написал читающий субагент. Кода у тебя нет, черновик ты не открываешь — только эти строки и числа. Остальные проверки Шага 4, включая сверку сущностей сверху, уже пройдены и добора не требуют.'
    echo; echo '### Шаг 3.0–3.1 (из SKILL.md)'; echo; sed -n "${R1},$((R2-1))p" "$SKILL"
    echo; echo '### Маркерный гейт (Шаг 4, из SKILL.md)'; echo; sed -n "${A1},$((A2-1))p" "$SKILL"
    echo; echo '---'; echo; cat "$c"; echo
    echo 'Реши маркерный гейт по этим правилам. Ответ — в таком виде:'
    echo '1. По каждому классу одной строкой: что дали маркеры, что в описи, что из этого следует по правилам.'
    echo '2. Если правила требуют добора — перечень добора для субагента, как велят правила, после строки `## Добор`. Не требуют — этого блока нет.'
    echo '3. Если правила велят строку в отчёт человеку — каждая такая строка отдельно, начиная с `ОТЧЁТ:`. Не велят — ни одной.'
    echo '4. Последней строкой — ровно одно из двух: `МАРКЕРЫ: ДОБОР` либо `МАРКЕРЫ: ПРОЙДЕН`.'
  } > "$OUT/$v/prompt.md"
  for i in $(seq 1 "$N"); do
    ( cd "$OUT/$v" && claude -p --model "$MODEL" --output-format json < prompt.md > "out-$i.json" 2> "err-$i.log"
      node -e 'const fs=require("fs");let j={};try{j=JSON.parse(fs.readFileSync(process.argv[1],"utf8"))}catch(e){};fs.writeFileSync(process.argv[2],j.result||"");fs.writeFileSync(process.argv[3],String(j.total_cost_usd||0))' "out-$i.json" "answer-$i.md" "cost-$i.txt"; rm -f "out-$i.json" ) &
  done
  wait
  echo "  $v — готов"
done
echo "ГОТОВО: $OUT"
