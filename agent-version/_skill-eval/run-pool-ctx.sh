#!/usr/bin/env bash
# run-pool-ctx.sh — пул прогонов для проб петли 5.0. Копия корневого `_skill-eval/run-pool.sh`
# с двумя правками, обе из замера 2026-08-14.
#
#   ./run-pool-ctx.sh <скилл.md> <промпт.txt> <каталог-плеча> <N> [параллельность] [засев]
#
# ПРАВКА 1 — УБРАНА ПОСЛЕДНЯЯ СТРОКА ПРОМПТА «Твой ответ — то, что ты сказал бы пользователю в чат».
#
# Она стоила половины замера. База по четырём пишущим пробам дала 12 прогонов из 40, которые
# выдали хендофф «спека готова, файл `docs/<KEY>/technical_specification.md`, статус такой-то» и
# НЕ СОЗДАЛИ ФАЙЛА; на `ts-ctx` таких было пять из десяти. Пилот `pilot-wrapper.sh` — та же
# фикстура, тот же снимок скилла, та же модель, отличие ровно в этой строке — дал спеку на диске
# в 5 прогонах из 5.
#
# Механика понятная: строка называет ответ в чат ЕДИНСТВЕННЫМ результатом работы. Прогон её
# исполняет — формулирует ответ, — а запись файла становится необязательной подготовкой к нему.
# Стенд мерил собственную формулировку и списывал её в дефект скилла.
#
# Урок тот же, что в `RUNNER.md`: обёртка не «оформление», она часть измеряемого. Меняешь
# обёртку — перезапускай пробу с нуля и не сравнивай с прежними числами.
#
# ПРАВКА 2 — ОТКАЗ API ОПОЗНАЁТСЯ СТРОЖЕ. Настоящее сообщение CLI — это ВЕСЬ вывод: короткий и с
# маркера в начале. Прежняя проверка искала маркер где угодно, и прогон, написавший в спеке
# «429 (rate limit)», уезжал в `_api-failure.txt` — то есть молча выпадал из знаменателя. На
# `ts-ctx` так пропали 2 прогона из 10, и именно те, что перенесли в спеку больше чужой
# конкретики: стенд врал в пользу скилла.

set -u

SKILL="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
PROMPT="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"
OUT="$3"
N="$4"
CONC="${5:-5}"
SEED="${6:-}"
# Папка с заглушками под-скиллов. Пусто → поведение ровно как прежде, и все пробы набора,
# гоняющие ОДИН скилл, изменения не замечают. Это их сторож.
STUBS_DIR="${7:-}"

[ -f "$SKILL" ]  || { echo "нет файла скилла: $SKILL";  exit 1; }
[ -f "$PROMPT" ] || { echo "нет файла промпта: $PROMPT"; exit 1; }
if [ -n "$SEED" ]; then
  [ -d "$SEED" ] || { echo "нет папки засева: $SEED"; exit 1; }
  SEED="$(cd "$SEED" && pwd)"
fi
if [ -n "$STUBS_DIR" ]; then
  [ -d "$STUBS_DIR" ] || { echo "нет папки заглушек: $STUBS_DIR"; exit 1; }
  STUBS_DIR="$(cd "$STUBS_DIR" && pwd)"
fi
# ХОД 2 — файл с репликой аналитика, которой он отвечает на хендофф под-скилла. Пусто → стенд
# одноходовой, как был, и прежние пробы этого не замечают. Зачем второй ход: у проб маршрута
# (`rt-*`) отказ наступает ИМЕННО на стыке — под-скилл кончает ход, и проводник должен продолжить
# сам. Одним ходом стык не воспроизводится: прогон отвечает выводом заглушки и останавливается,
# а в живой сессии там стоит реплика человека. Текст реплики держать НЕЙТРАЛЬНЫМ («да, годится»):
# любое «продолжай маршрут» превращает стенд в подсказку, и мерить он будет себя.
TURN2="${8:-}"
if [ -n "$TURN2" ]; then
  [ -f "$TURN2" ] || { echo "нет файла второго хода: $TURN2"; exit 1; }
  TURN2="$(cd "$(dirname "$TURN2")" && pwd)/$(basename "$TURN2")"
fi
mkdir -p "$OUT"

# Настоящий отказ CLI: короткий вывод либо маркер в первых 200 байтах.

# ─── Две ручки стенда, обе через окружение и обе ВЫКЛЮЧЕНЫ ПО УМОЛЧАНИЮ ──────────────────────
# Умолчание здесь не вкусовое: этот раннер гоняет ВЕСЬ набор проб петли (`ts-*`, `br-*`, `rv-*`,
# `cdoc-*`, `bg-*`, `sr-*`). Любая правка, меняющая поведение молча, обнуляет их базы разом —
# ровно тот класс дефекта, что описан в шапке про строку «твой ответ — то, что ты сказал бы
# пользователю в чат». Поэтому: пусто → команда запуска побайтно прежняя.
#
# `EFFORT` — глубина размышления модели (`--effort low|medium|high|xhigh|max`). Пусто → флаг не
# передаётся вовсе и работает умолчание CLI. Замер 2026-08-20 на haiku: `low` → 629 выходных
# токенов и 5.8с, `max` → 1609 и 15.9с, то есть ручка рабочая и цену двигает заметно.
EFFORT="${EFFORT:-}"
# `RT_MAX_TURNS` — потолок ходов в цикле «реплика аналитика». Действует только там, где задан
# файл реплики (восьмой аргумент), то есть на пробах маршрута. Остальной набор одноходовой и
# цикла не видит.
MAX_TURNS="${RT_MAX_TURNS:-8}"

is_api_failure() {
  local f="$1"
  local size; size=$(wc -c < "$f")
  if [ "$size" -lt 600 ]; then
    grep -qiE "API Error|Request not allowed|Please run /login|Credit balance|rate limit|session limit|usage limit" "$f"
  else
    head -c 200 "$f" | grep -qiE "API Error|Request not allowed|Please run /login|Credit balance|rate limit|session limit|usage limit"
  fi
}

# Состав засева на момент старта плеча — эталон для сверки перед каждым прогоном.
SEED_FILES=""
if [ -n "$SEED" ]; then
  SEED_FILES="$(cd "$SEED" && find . -type f | sed 's|^\./||' | sort | tr '\n' ' ')"
fi

# Достаёт текст последнего `result` из потока в файл. Вынесено из тела прогона: ходов стало два,
# извлечение нужно обоим.
extract_answer() {
  local stream="$1" out="$2" err="$3"
  node -e '
    const fs = require("fs")
    const lines = fs.readFileSync(process.argv[1], "utf8").trim().split("\n")
    const parsed = lines.map((s) => { try { return JSON.parse(s) } catch { return null } }).filter(Boolean)
    // ПОСЛЕДНИЙ результат, а не первый: скилл с субагентами печатает `result` на каждом своём ходе.
    // `find` брал первый, и прогоны выглядели пустой работой при готовых отчётах в потоке.
    const results = parsed.filter((x) => x.type === "result" && typeof x.result === "string")
    const res = results.length ? results[results.length - 1] : null
    fs.writeFileSync(process.argv[2], res ? res.result : "")
  ' "$stream" "$out" 2>>"$err" || cp /dev/null "$out"
}

# Длина трассы — признак ДВИЖЕНИЯ маршрута. Считаются непустые строки: заглушка пишет по строке
# на вызов. Файла нет (ни один под-скилл не вызван) → ноль, а не ошибка.
trace_len() {
  local f="$1/_trace.log"
  [ -f "$f" ] || { echo 0; return; }
  grep -c '[^[:space:]]' "$f" 2>/dev/null || echo 0
}

run_one() {
  local i="$1"
  local sb="$OUT/run-$i"
  # Стоп-файл: если засев испорчен, остальные прогоны не запускаются — испорченное плечо
  # дешевле не доганять, чем потом опознавать.
  if [ -e "$OUT/_STOP" ]; then echo "  run-$i — СТОП, плечо остановлено"; return 0; fi
  mkdir -p "$sb"
  if [ -s "$sb/answer.md" ]; then echo "  run-$i — уже есть, пропуск"; return 0; fi
  local abs_sb; abs_sb="$(cd "$sb" && pwd)"

  if [ -n "$SEED" ]; then
    # СВЕРКА ЗАСЕВА ПЕРЕД КАЖДЫМ ПРОГОНОМ, а не один раз на плечо. Прогон, промахнувшийся мимо
    # своей песочницы, пишет результат в соседнюю папку — и если это папка засева, все следующие
    # прогоны получают готовый документ. 2026-08-14: так было испорчено целое плечо и пилот, и
    # заметили это только по `_seeded.txt`. Сверка стоит одну команду и ловит порчу на первом же
    # прогоне после неё.
    local now; now="$(cd "$SEED" && find . -type f | sed 's|^\./||' | sort | tr '\n' ' ')"
    if [ -n "${SEED_FILES:-}" ] && [ "$now" != "$SEED_FILES" ]; then
      echo "  run-$i — ЗАСЕВ ИСПОРЧЕН, плечо остановлено"
      echo "    было: $SEED_FILES"
      echo "    стало: $now"
      touch "$OUT/_STOP"
      return 1
    fi
    cp -r "$SEED"/. "$abs_sb"/ 2>/dev/null
    ( cd "$abs_sb" && find . -type f -not -name '_seeded.txt' | sed 's|^\./||' | sort ) > "$abs_sb/_seeded.txt"
  fi

  # ЗАГЛУШКИ ПОД-СКИЛЛОВ. Кладутся в `.claude/skills/` песочницы — так они становятся НАСТОЯЩИМИ
  # скиллами в реестре, а не файлами по пути: вызвать то, чего в реестре нет, модель не может, а
  # не найдя под-скилл — делает его работу сама, и проба меряет уже не маршрут.
  #
  # Зачем заглушки, а не живые под-скиллы: мерится ПЕРЕХОД ПО ШАГАМ, а не содержание документов.
  # Живой набор стоит десятки тысяч токенов на прогон и добавляет свою дисперсию поверх той,
  # которую мы измеряем. Прецедент — `SM-HANDOFF`: «ответ субагента подменён заглушкой — это цена
  # детерминированности».
  if [ -n "$STUBS_DIR" ]; then
    mkdir -p "$abs_sb/.claude/skills"
    cp -r "$STUBS_DIR"/. "$abs_sb/.claude/skills"/ 2>/dev/null
  fi

  local task="Твоя рабочая директория — ${abs_sb}. Считай её корнем рабочего репозитория. Ничего за её пределами не создавай и не изменяй: путь, ведущий наружу, — ошибка сборки пути, а не повод писать туда.

Прочитай целиком файл ${SKILL} — это скилл. Дальше действуй строго по нему, как если бы он был загружен командой /skill.

Интерактивного инструмента вопросов (AskUserQuestion) в этом окружении нет. Если по скиллу нужно задать вопросы — задавай их обычным текстом.

Сообщение пользователя лежит в файле ${PROMPT}. Прочитай его и отработай по скиллу."

  # Строка про под-скиллы добавляется ТОЛЬКО когда заглушки есть. Без неё смоук 2026-08-18 показал,
  # почему она обязательна: инструмент вызова скиллов у прогона в списке был, заглушки в
  # `.claude/skills/` лежали, но промпт говорил лишь «прочитай файл по пути — это скилл», и
  # оркестратор НИ РАЗУ никого не вызвал — написал документ сам. Это отказ стенда, а не дефект
  # маршрута: измеряемое поведение (какой под-скилл вызван) просто не могло проявиться.
  if [ -n "$STUBS_DIR" ]; then
    task="$task

Под-скиллы петли установлены в реестре скиллов этой песочницы. Когда твой скилл велит запустить под-скилл — запускай его инструментом вызова скиллов по имени, а не выполняй его работу сам и не пиши его файлы за него."
  fi

  # `WRAPPER_CHAT_LINE=1` возвращает ту самую строку — только для A/B-замера самой обёртки.
  # В обычных прогонах она не ставится: см. шапку файла.
  if [ "${WRAPPER_CHAT_LINE:-0}" = "1" ]; then
    task="$task
Твой ответ — то, что ты сказал бы пользователю в чат."
  fi

  # ПОТОК ВЫЗОВОВ СОХРАНЯЕТСЯ, `answer.md` ОСТАЁТСЯ ПРЕЖНИМ. Без потока побег из песочницы
  # неотличим от фантомной записи: снаружи оба выглядят как «отчитался о файле, файла нет», но
  # первый — отказ стенда и обязан выпадать из знаменателя, второй — дефект скилла и обязан в нём
  # оставаться. На раунде 2026-08-18 (`bf-spec`) их пришлось разделять догадкой, и числа вышли
  # верхней оценкой. `check-escape.mjs` умеет разбирать этот поток с 2026-08-08 — ему не хватало
  # только самого потока.
  #
  # `answer.md` собирается из поля `result` терминального события, то есть побайтно равен прежнему
  # stdout: все грейдеры набора читают его и меняться не должны.
  # Свой `session-id` на песочницу: по нему второй ход находит сессию первого. Генерится node —
  # он в наборе есть везде (на нём грейдеры), `uuidgen` под Git Bash нет.
  local sid; sid="$(node -e 'console.log(require("crypto").randomUUID())')"
  ( cd "$sb" && timeout 900 claude -p "$task" --model haiku --permission-mode bypassPermissions \
        ${EFFORT:+--effort "$EFFORT"} \
        --session-id "$sid" --output-format stream-json --verbose ) \
      > "$sb/stream.jsonl" 2> "$sb/_stderr.log"
  local rc=$?
  extract_answer "$sb/stream.jsonl" "$sb/answer.md" "$sb/_stderr.log"

  # ─── ХОДЫ 2…K: реплика аналитика в ТУ ЖЕ сессию, ПОКА МАРШРУТ ДВИЖЕТСЯ ──────────────────────
  # `--resume` продолжает разговор первого хода: контекст, прочитанный скилл и записанные файлы
  # на месте, песочница та же, `_trace.log` продолжает накапливаться. Это и есть живая
  # последовательность «под-скилл отдал файл → человек ответил → проводник идёт дальше».
  #
  # ПОЧЕМУ ЦИКЛ, А НЕ ОДИН ВТОРОЙ ХОД (правка 2026-08-20). Фиксированные два хода мерили не то:
  # один ход двигает маршрут на ОДИН шаг, а маршруту дефекта нужно шесть (репорт → приёмка →
  # спека → приёмка → этапы → приёмка). Прогон обрывали на втором шаге и записывали в дефект
  # скилла то, что было пределом стенда: `rt-bug` не давал зелёных НИКОГДА (0/7, 0/7, 0/10, 1/10).
  #
  # ПРИЗНАК ДВИЖЕНИЯ — РОСТ ТРАССЫ, А НЕ ДЛИНА ОТВЕТА. Трассу пишут заглушки, вызванные
  # по-настоящему; ответ агента может пересказывать намерение, ничего не вызвав. Правило репы
  # «грейдить файл, а не формулировку» действует и на условие остановки.
  #
  # ОСТАНОВКА — ДВА ХОДА ПОДРЯД БЕЗ РОСТА ТРАССЫ. Один пустой ход законен: агент кончает ход
  # вопросом к аналитику и на нейтральное «да, годится» делает следующий шаг. Два подряд значит,
  # что реплика больше не расшевеливает, и дальше мы платим за пустые ходы.
  # Потолок `RT_MAX_TURNS` — страховка от бесконечного круга, а не рабочее ограничение.
  local idle=0 turn=1 apifail=0
  if [ -n "$TURN2" ] && [ $rc -eq 0 ] && [ -s "$sb/answer.md" ] && ! is_api_failure "$sb/answer.md"; then
    cp "$sb/answer.md" "$sb/answer-01.md"
    local reply; reply="$(cat "$TURN2")"
    while [ "$turn" -lt "$MAX_TURNS" ] && [ "$idle" -lt 2 ]; do
      local before; before="$(trace_len "$sb")"
      turn=$((turn + 1))
      ( cd "$sb" && timeout 900 claude -p "$reply" --model haiku --permission-mode bypassPermissions \
            ${EFFORT:+--effort "$EFFORT"} \
            --resume "$sid" --output-format stream-json --verbose ) \
          > "$sb/stream-$(printf '%02d' "$turn").jsonl" 2>> "$sb/_stderr.log"
      rc=$?
      extract_answer "$sb/stream-$(printf '%02d' "$turn").jsonl" "$sb/answer-$(printf '%02d' "$turn").md" "$sb/_stderr.log"
      # Отказ API на любом ходу обрывает цикл: продолжать нечего, и склейка ниже отдаст
      # грейдеру то, что успело накопиться, вместе с маркером отказа.
      # `is_api_failure` принимает ПУТЬ, а не текст. Пустой файл хода — тоже обрыв: продолжать
      # диалог, в котором ход ничего не вернул, значит платить за пустые ходы.
      local last="$sb/answer-$(printf '%02d' "$turn").md"
      if [ ! -s "$last" ] || { [ -s "$last" ] && is_api_failure "$last"; }; then apifail=1; break; fi
      if [ $rc -ne 0 ]; then apifail=1; break; fi
      local after; after="$(trace_len "$sb")"
      if [ "$after" -gt "$before" ]; then idle=0; else idle=$((idle + 1)); fi
    done
    # `answer.md` — склейка ВСЕХ ходов: грейдеры набора читают именно его и ищут в нём анкеры
    # (спрошен ли ключ, показано ли меню). Склейка сохраняет находки каждого хода.
    cat "$sb"/answer-*.md > "$sb/answer.md"
    # ОТКАЗ API ПОСРЕДИ ЦИКЛА НЕ ДОЛЖЕН ВЫГЛЯДЕТЬ КАК ОБРЫВ МАРШРУТА. Проверка ниже смотрит на
    # склейку, а склейка длинная — маркер отказа в ней уезжает за первые 200 байт и не находится.
    # Прогон, потерявший API на четвёртом ходу, записался бы в «скилл встал на третьей станции».
    # Поэтому ставим отдельный маркер, и грейдер выкидывает такой прогон из знаменателя.
    if [ "$apifail" = "1" ]; then
      echo "ход $turn: отказ API или пустой ответ" > "$sb/_api-failure-turn.txt"
      echo "  run-$i — ОТКАЗ API на ходу $turn, песочница помечена и в счёт не идёт"
      return 0
    fi
    echo "  run-$i — ходов: $turn, строк в трассе: $(trace_len "$sb")"
  fi

  if [ -s "$sb/answer.md" ] && is_api_failure "$sb/answer.md"; then
    mv "$sb/answer.md" "$sb/_api-failure.txt"
    echo "  run-$i — ОТКАЗ API, песочница помечена и в счёт не идёт"
    return 0
  fi
  if [ $rc -ne 0 ]; then
    echo "  run-$i — ОТКАЗ (rc=$rc), см. $sb/_stderr.log"
  else
    echo "  run-$i — готов"
  fi
}

echo "плечо: $OUT"
echo "скилл: $SKILL"
echo "промпт: $PROMPT"
echo "прогонов: $N, параллельно: $CONC"

running=0
for i in $(seq -w 1 "$N"); do
  run_one "$i" &
  running=$((running + 1))
  if [ "$running" -ge "$CONC" ]; then wait -n 2>/dev/null || wait; running=$((running - 1)); fi
done
wait

echo "ГОТОВО: $OUT — песочниц с ответом: $(find "$OUT" -name answer.md -size +0 | wc -l) из $N"
