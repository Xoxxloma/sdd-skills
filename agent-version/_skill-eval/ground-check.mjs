const ORD = ['перв', 'втор', 'трет', 'четверт', 'пят', 'шест', 'седьм', 'восьм', 'девят', 'десят',
  ...teens, 'двадцат', 'тридцат']
const ORD_END = /^(ый|ий|ой|ого|ому|ым|ом|ая|ья|ую|ье|ое|ые|ых|ыми|ей|ьей|ьего|ьему|ьим|ьем|ья|ью|ьи)$/
// Дробь: знаменатель во множественном после числителя 2–9 — «две трети», «двух третей», «три пятых».
const FRAC_END = /^(и|ей|ям|ями|ях|ых|ым|ыми)$/
function fracDen (w) {
  for (let i = 2; i < 10; i++) {
    const st = ORD[i]
    if (w.startsWith(st) && FRAC_END.test(w.slice(st.length))) return i + 1
  }
  return null
}
function ordinal (w) {
  for (let i = ORD.length - 1; i >= 0; i--) {
    const st = ORD[i]
    if (w.startsWith(st) && ORD_END.test(w.slice(st.length))) return i < 10 ? i + 1 : i < 19 ? i + 1 : (i === 19 ? 20 : 30)
  }
  return null
}
const MULT = { тысяча: 1e3, тысячи: 1e3, тысяч: 1e3, тысячу: 1e3, тысячам: 1e3, тысячами: 1e3, миллион: 1e6, миллиона: 1e6, миллионов: 1e6 }

function wordVal (w) { return w in W ? W[w] : null }

// Значения чисел в тексте: цифры (с пробелами-разделителями тысяч, дроби, время «16:00» → 16) и числа словами,
// составные («двадцать четыре» → 24, «две тысячи» → 2000). withParts — ещё и слагаемые (для источника).
export function numbersOf (text, withParts = false) {
  // Метки времени расшифровки — не факты встречи: `10:05:12` в чате, `00:01:02,000 --> …` в VTT/SRT, номер блока SRT.
  // Иначе секунды и минуты меток дают опору любому числу до 59.
  const t = norm(stripRefs(text))
    .replace(/^.*-->.*$/gm, ' ')
    .replace(/^\s*\d+\s*$/gm, ' ')
    .replace(/\d{1,2}:\d{2}:\d{2}(?:[.,]\d+)?/g, ' ')
  const out = []
  const s = t.replace(/(\d{1,2}):(\d{2})/g, (_, h, m) => ` ${h}${m === '00' ? '' : ' ' + m} `)
    .replace(/(\d{1,3})(?: (\d{3}))+(?!\d)/g, (m) => m.replace(/ /g, ''))
  for (const m of s.matchAll(/\d+(?:[.,]\d+)?/g)) out.push(Number(m[0].replace(',', '.')))
  const words = s.split(/[^а-яa-z]+/).filter(Boolean)
  // Составное — только разряд после разряда покрупнее: «двадцать четыре», «сто пятьдесят»; «шесть — полтора, два» — три
  // числа. Одиночное «один» в выходе — неопределённое «один человек», не число (в источнике — число).
  let total = 0, cur = 0, any = false, last = 0, n = 0, loneOne = false
  const flush = () => { if (any && !(loneOne && n === 1 && !total && !withParts)) out.push(total + cur); total = 0; cur = 0; any = false; last = 0; n = 0; loneOne = false }
  const joins = (v) => Number.isInteger(v) && Number.isInteger(last) && ((last >= 100 && last % 100 === 0 && v < 100) || (last >= 20 && last < 100 && last % 10 === 0 && v < 10))
  for (const w of words) {
    const v = wordVal(w)
    if (v !== null) {
      if (withParts) out.push(v)
      if (any && cur && !joins(v)) flush()
      cur += v; any = true; last = v; n++; loneOne = v === 1 && W[w] === 1 && n === 1
      continue
    }
    if (w in MULT) { total += (cur || 1) * MULT[w]; cur = 0; any = true; continue }
    // Дробь: числитель и знаменатель — отдельные числа, не сумма («двух третей» — 2 и 3, не 5).
    const fd = any && cur >= 2 && cur <= 9 && !total ? fracDen(w) : null
    if (fd !== null) { flush(); out.push(fd); continue }
    // Порядковое замыкает составное: «четыреста двадцать девятая» — 429, а не 420 и 9.
    const o = ordinal(w)
    if (o !== null && any) { cur += o; flush(); continue }
    flush()
    if (o !== null) out.push(o)
  }
  flush()
  return out
}

// ── люди и роли ──────────────────────────────────────────────────────────────────────────────────────────
// Поля людей: `решил:` / `решает:` / `ждёт:` — только с двоеточием (без него это глагол в тексте: «ждёт возврата»);
// `со слов <кто>` — без двоеточия; `принял <кто>` (протокол по памяти) — без двоеточия, берутся только слова с заглавной.
const PERSON_FIELD = /(?:^|[^а-яёa-z])(?:(решил[аи]?|решает|жд[её]т)\s*:|(со\s+слов)\s|(принял[аи]?)\s*:?\s)\s*([^·;\n]+)/gi
const STOP = new Set(['аналитик', 'аналитика', 'аналитиком', 'не', 'помню', 'нет', 'и', 'или', 'у', 'кто', 'из', 'от',
  'со', 'слов', 'уточнить', 'знаю', 'никто', 'все', 'всех', 'вместе', 'сам', 'сама', 'сами', 'по', 'памяти',
  'неизвестно', 'неизвестен', 'неизвестна', 'никого', 'пока', 'уточняется', 'решено', 'уверен', 'уверена',
  'что', 'какое', 'какой', 'какая', 'какие', 'это', 'этот', 'эта', 'уточняет', 'уточнит', 'ответит', 'ответ', 'для',
  'при', 'про', 'его', 'ее', 'их', 'она', 'они', 'тот', 'там', 'тоже', 'кого',
  // «со слов участников встречи», «говорящий не назван» — не имя.
  'участник', 'участники', 'участников', 'встречи', 'встреча', 'говорящий', 'говорящего', 'назван'])
export const stemOf = (w) => { const x = norm(w); return x.slice(0, Math.max(3, Math.min(5, x.length - 2))) }

// Слова людей и ролей из полей пункта: «решил: Иванова А.», «ждёт: служба безопасности», «со слов Петрова».
export function personWords (text) {
  const res = []
  // `;` внутри скобок («Инга (предложил Роберт; Милана согласна)») — не конец поля.
  const t = stripRefs(text).replace(/\(([^)]*)\)/g, (m) => m.replace(/;/g, ','))
  for (const m of t.matchAll(PERSON_FIELD)) {
    const capsOnly = !!m[3]
    // Сначала скобки целиком («решил: Хабибуллин (предложил Дьячков)»), потом обрыв на непарной `)` и `→`
    // («(со слов Ильина М.) → как должно стать»).
    const val = m[4].replace(/\(.*?\)/g, ' ').split(/[)→]/)[0].replace(/\s[—–-]\s.*$/, '')
    // После первой запятой — продолжение фразы («…, подтвердил Пантелеев», «…, после ответа владельца»): из него
    // берутся только слова с заглавной — имена; строчные слова там не люди и не роли.
    val.split(',').forEach((seg, i) => {
      for (const w of seg.split(/[^А-ЯЁа-яёA-Za-z]+/)) {
        if (w.length < 3 || STOP.has(norm(w))) continue
        if ((capsOnly || i > 0) && !/^[А-ЯЁA-Z]/.test(w)) continue
        res.push(w)
      }
    })
  }
  return res
}

// Слова шапки «> Встреча: … участники: роль — Фамилия И. О.; …»: и роли, и имена.
export function headerWords (line) {
  // «аналитик — автор протокола / заметок» — сам аналитик о себе, не роль на встрече.
  const m = String(line || '').replace(/\r/g, '').replace(/автор\S*\s+(протокол|заметок|записей|конспект)\S*/gi, ' ')
    .match(/участники:\s*(.*)$/i)
  if (!m) return []
  return m[1].split(/[^А-ЯЁа-яёA-Za-z]+/).filter((w) => w.length >= 3 && !STOP.has(norm(w)) &&
    !/^(по|памяти|онлайн|очно)$/i.test(w))
}

const LATIN = /[A-Za-z][A-Za-z0-9]*(?:[-_./][A-Za-z0-9]+)*/g
export const latinOf = (text) => [...stripRefs(text).matchAll(LATIN)].map((m) => m[0]).filter((x) => x.length >= 2)

function hasStem (srcN, w) {
  const st = stemOf(w)
  const re = new RegExp('(^|[^а-яa-z])' + st.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
  return re.test(srcN)
}

// out — текст выхода (пункт, строка входа, шапка); src — текст источника, или массив текстов.
// opts.skip — токены, которые не проверять (нормализованные); opts.header — out это строка шапки.
export function groundCheck (out, src, opts = {}) {
  const srcText = Array.isArray(src) ? src.join('\n') : String(src || '')
  const srcN = norm(srcText)
  const skip = new Set((opts.skip || []).map(norm))
  const missing = []
  const srcNums = new Set(numbersOf(srcText, true))
  // Час в 24-часовой записи — пересчёт, а не выдумка: «до 21:00» при «до девяти вечера».
  const hour24 = (v) => v >= 13 && v <= 24 && srcNums.has(v - 12)
  for (const v of numbersOf(out)) if (!srcNums.has(v) && !hour24(v) && !skip.has(String(v))) missing.push({ kind: 'число', tok: String(v) })
  const soft = []
  const ppl = opts.header ? headerWords(out) : personWords(out)
  for (const w of ppl) if (!skip.has(norm(w)) && !hasStem(srcN, w)) missing.push({ kind: 'человек', tok: w })
  for (const l of latinOf(out)) {
    const ln = norm(l)
    if (skip.has(ln)) continue
    const re = new RegExp('(^|[^a-z0-9])' + ln.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '($|[^a-z0-9])')
    if (!re.test(srcN)) missing.push({ kind: 'латиница', tok: l })
  }
  const seen = new Set()
  const uniq = missing.filter((x) => { const k = x.kind + x.tok; if (seen.has(k)) return false; seen.add(k); return true })
  return { ok: uniq.length === 0, missing: uniq, soft }
}

export const fmtMissing = (r) => r.missing.map((x) => `${x.kind} «${x.tok}»`).join(', ')

