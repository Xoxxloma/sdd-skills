export const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[   ]/g, ' ')

// Ссылки на источник — не факты пункта: `· L57`, `· 2026-10-14 №1`, `· 2026-10-14 №1.2`, `L12–L15`, `№3`; пометки
// состояния ноута 2.0.0 (` ‖ заменён: 2026-10-20 №1.1`) — тоже.
export function stripRefs (s) {
  return String(s || '')
    .replace(/\s‖[^\n]*$/gm, '')
    .replace(/\s·\s*(L\d+|сообщение|\d{4}-\d{2}-\d{2}\s*№\s*\d+)[^\n]*$/gm, '')
    .replace(/\bL\d+(\s*[–—-]\s*L?\d+)?/g, ' ')
    .replace(/\d{4}-\d{2}-\d{2}(\s*№\s*\d+(\.\d+)?)?/g, ' ')
    .replace(/№\s*\d+(\.\d+)?/g, ' ')
}

