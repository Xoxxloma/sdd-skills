    /^### / { h = substr($0, 5); p = index(h, " — "); if (p > 0) h = substr(h, 1, p - 1); gsub(/`/, "", h); gsub(/^[ \t]+|[ \t]+$/, "", h); bk = h; blk[bk] = 1 }
