  END {
    split("контракт сущности задачи", L, " ")
    for (i = 1; i <= 3; i++) printf "%s %d (с телом %d, пустых %d)\n", L[i], n[L[i]], b[L[i]], n[L[i]] - b[L[i]]
    printf "топики %d (потребляет %d, публикует %d)\n", n["топики"], tp, tu
