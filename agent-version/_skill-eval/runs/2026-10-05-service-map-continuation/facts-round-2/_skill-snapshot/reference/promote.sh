#!/usr/bin/env bash
# promote.sh — продвижение черновика без модели: копия байт-в-байт и три счёта сверки.
#
#   bash promote.sh <черновик> <куда> [<идентификатор запуска>]
# Неразобранный кандидат в _pending не затирается: при коллизии нужен идентификатор запуска.
#
# Пишет только <куда> (папку создаёт). Копия идёт во временный файл рядом и переносится на место
# только после сверки — прежняя карточка при любом сбое остаётся как была. Печатает счёты `^### `,
# `^| ` и всех строк по обоим файлам и итог «КОПИЯ ВЕРНА → <куда>» либо «КОПИЯ РАСХОДИТСЯ — не
# записано» (код 4).
set -u
SRC="${1:?черновик}"; DST="${2:?куда}"; RUN="${3:-}"
fail() { echo "КОПИЯ РАСХОДИТСЯ — не записано: $*"; [ -n "${TMP:-}" ] && rm -f "$TMP"; exit 4; }
[ -f "$SRC" ] || { echo "НЕТ ФАЙЛА: $SRC"; exit 2; }
[ -d "$DST" ] && fail "«$DST» — папка, а не путь карточки"
if [ "$(basename "$(dirname "$DST")")" = _pending ] && [ -e "$DST" ]; then
  case "$RUN" in ''|*[!A-Za-z0-9_-]*) fail "кандидат уже существует; нужен уникальный идентификатор запуска" ;; esac
  BASE="${DST%.md}.$RUN"; DST="$BASE.md"; n=1
  while [ -e "$DST" ]; do DST="$BASE.$n.md"; n=$(( n + 1 )); done
fi
mkdir -p "$(dirname "$DST")" 2>/dev/null || fail "не создаётся папка $(dirname "$DST")"
TMP="$DST.promote.$$"
cp "$SRC" "$TMP" 2>/dev/null || fail "копия не сделана"
cnt() { printf '%s %s %s' "$(grep -c '^### ' "$1")" "$(grep -c '^| ' "$1")" "$(wc -l < "$1" | tr -d ' ')"; }
a=$(cnt "$SRC"); b=$(cnt "$TMP")
echo "черновик: ### | строк — $a"
echo "копия:    ### | строк — $b"
[ "$a" = "$b" ] && cmp -s "$SRC" "$TMP" || fail "счёты или байты разошлись"
mv -f "$TMP" "$DST" || fail "перенос на место не удался"
echo "КОПИЯ ВЕРНА → $DST"
