# copy-once.sh — копия в журнальный снимок раунда (`<раунд>/_skills/`) один раз и атомарно.
# Подключается раннерами: `. "$HERE/copy-once.sh"`.
#
#   copy_once <источник> <цель>
#
# «Цели нет — копирую» гонится: две пробы одного скилла, стартовав вместе, обе видят пустое место, и
# второй `cp -r` кладёт папку ВНУТРЬ уже созданной (`<скилл>.reference/reference/`) — прогон читает не
# тот текст. Копия идёт во временное имя и встаёт на место одним `mv -T`: успел первый — второй свою
# копию выбрасывает.
copy_once() {
  [ -e "$2" ] && return 0
  local tmp="$2.tmp.${BASHPID:-$$}"
  cp -r "$1" "$tmp" || { rm -rf "$tmp"; return 1; }
  mv -T "$tmp" "$2" 2>/dev/null || rm -rf "$tmp"
  return 0
}
