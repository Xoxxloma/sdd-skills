// ─── Ключ читается из фикстуры, а не дублируется здесь ──────────────────────────────────────
// Дублирование ключа в грейдере — способ разойтись с ним на первой же правке. Ключ один, лежит
// в `KEY.md`, сторожится `check-key-sr-verify.mjs`.
function loadKey () {
  const t = readFileSync(new URL('./fixtures/SR-VERIFY/KEY.md', import.meta.url), 'utf8')
  const key = {}
  for (const row of t.split('\n').filter(l => /^\|\s*\d+\s*\|/.test(l))) {
    const c = row.split('|').map(x => x.trim())
    const v = c[3].toUpperCase()
    key[Number(c[1])] = v.startsWith('НЕ ОТВЕЧАЕТ') ? 'no' : v.startsWith('СПОРНЫЙ') ? 'moot' : 'yes'
  }
  return key
}

// Обе функции ниже — копия из `grade-sr.mjs`. Копия, а не импорт: тот файл скрипт, а не модуль,
// и экспортировать из него значит переписать его целиком ради второй пробы. Разойтись им нечем —
// обе разбирают одну и ту же форму отчёта, и обе покрыты самотестами своих файлов.
function carryGroupHeaders (text) {
  const HEAD = /^[*#>\s]{0,4}(§[^\n]{0,80}|\[свод\][^\n]{0,80})$/
  const ITEM = /^\s+(?:[-*•]|\d+[.)])\s/
  let head = ''
  return text.split('\n').map(line => {
    if (!line.trim()) { head = ''; return line }
    if (!ITEM.test(line) && HEAD.test(line)) { head = line.replace(/^[*#>\s]+/, '').trim(); return line }
    if (head && ITEM.test(line)) return line.replace(/^(\s*(?:[-*•]|\d+[.)])\s*)/, m => m + head + ' — ')
    return line
  }).join('\n')
}

function splitUnits (text) {
  return carryGroupHeaders(text)
    .split(/\n\s*\n/)
    .flatMap(b => b.split(/\n(?=\s*(?:[-*•]|#{1,6}\s|\d+[.)]))/))
    .map(u => u.trim())
    .filter(Boolean)
}

const RE_ASKED = /вопросов задано[:*\s]+(\d+)/i
const RE_CLOSED = /закрыто цитатой[:*\s]+(\d+)/i
// Разбивка закрытий по разделам — правка А2, ради которой недоделанную сверку станет видно.
const RE_BREAKDOWN = /закрыто цитатой[:*\s]+\d+\s*\(/i

function gradeOne (dir, key) {
  const a = join(dir, 'answer.md')
  if (existsSync(join(dir, '_api-failure.txt'))) return { measured: false, why: 'отказ API' }
  if (!existsSync(a)) return { measured: false, why: 'нет answer.md' }
  const text = readFileSync(a, 'utf8')
  if (!text.trim()) return { measured: false, why: 'пустой answer.md' }

  // РОЛИ ЗАПУСКАТЬ БЫЛО НЕ НУЖНО. Проба подаёт их ответы готовыми; прогон, поднявший субагентов,
  // мерил не то и стоил вчетверо дороже. Это отказ стенда, а не дефект скилла: в знаменатель он
  // не идёт, но печатается — по нему видно, что строка промпта про Шаги 1–2 перестала работать.
  const st = join(dir, 'stream.jsonl')
  const agents = existsSync(st) ? (readFileSync(st, 'utf8').match(/"name":"Agent"/g) || []).length : 0
  if (agents > 0) return { measured: false, why: `запустил ${agents} субагент(ов) вопреки промпту` }

  const units = splitUnits(text)
  const alive = {}, touched = {}
  for (const [n, , reObj, reAx] of Q) {
    alive[n] = units.some(u => reObj.test(u) && reAx.test(u))
    // ТЕМА ЗАТРОНУТА — совпала хотя бы одна половина пары. Нужна не для зачёта, а чтобы не
    // объявлять ложное закрытие там, где вопрос в отчёте есть и просто переписан.
    touched[n] = alive[n] || units.some(u => reObj.test(u) || reAx.test(u))
  }

  // ЛОЖНОЕ ЗАКРЫТИЕ ОБЪЯВЛЯЕТСЯ, ТОЛЬКО ЕСЛИ ТЕМЫ В ОТЧЁТЕ НЕТ ВОВСЕ.
  //
  // Разбор 2026-08-21: из девятнадцати обвинений на плече «до» шестнадцать оказались промахом
  // анкера — вопрос стоял в отчёте другими словами. Схлопывание по оси переименовывает объект
  // («POST /v1/passes/decisions» → «одновременные решения»), и пара «объект + ось» рассыпается.
  //
  // Красное число обязано быть строгим в свою сторону: лучше недосчитать ложное закрытие, чем
  // придумать его. Придуманное ложное закрытие заставляет откатывать работающую правку —
  // это и произошло, и стоило дня.
  let closedRight = 0, closedWrong = 0, missed = 0, moot = 0, unclear = 0
  const wrongList = [], unclearList = []
  for (const [n, title] of Q) {
    const k = key[n]
    if (k === 'moot') { moot++; continue }
    if (alive[n]) { if (k === 'yes') missed++; continue }
    if (touched[n]) { unclear++; unclearList.push(`${n}. ${title}`); continue }
    if (k === 'no') { closedWrong++; wrongList.push(`${n}. ${title}`) } else closedRight++
  }

  const items = (text.match(/^[ \t]*\d+[.)][ \t]/gm) || []).length
  const axis = re => units.filter(u => re.test(u)).length
  return {
    measured: true,
    closedWrong, closedRight, missed, moot, wrongList, items, unclear, unclearList,
    asked: (text.match(RE_ASKED) || [])[1] ?? null,
    closed: (text.match(RE_CLOSED) || [])[1] ?? null,
    breakdown: RE_BREAKDOWN.test(text),
    axRepeat: axis(/повторн|дважды|двойн/i),
    axConfirm: axis(/подтвержд/i),
  }
}

// ─── Самотест: анкеры против самого входа ───────────────────────────────────────────────────
// Единственная бесплатная проверка, которая ловит плохой анкер до прогонов. Каждый из сорока
// вопросов `roles-output.md` обязан совпасть со своим анкером. Пересечения с чужими вопросами
// здесь законны: два вопроса про одну кнопку отличаются только осью.
function selftest () {
  const roles = readFileSync(new URL('./fixtures/SR-VERIFY/roles-output.md', import.meta.url), 'utf8')
  const lines = roles.split('\n').filter(l => /^Q \|/.test(l))
  let bad = 0
  if (lines.length !== 40) { console.log(`  ✗ во входе ${lines.length} вопросов, ждали 40`); bad++ }
  for (const [n, title, reObj, reAx] of Q) {
    const src = lines[n - 1]
    if (!src) { console.log(`  ✗ ${n} (${title}): нет строки во входе`); bad++; continue }
    if (!reObj.test(src)) { console.log(`  ✗ ${n} (${title}): анкер ОБЪЕКТА не совпал с «${src.slice(0, 90)}»`); bad++ }
    if (!reAx.test(src)) { console.log(`  ✗ ${n} (${title}): анкер ОСИ не совпал с «${src.slice(0, 90)}»`); bad++ }
  }
  const key = loadKey()
  if (Object.keys(key).length !== 40) { console.log(`  ✗ в ключе ${Object.keys(key).length} строк, ждали 40`); bad++ }
  console.log(bad === 0 ? 'самопроверка: ок — все сорок анкеров опознают свой вопрос' : `самопроверка: ПРОВАЛЕНА, расхождений ${bad}`)
  process.exit(bad === 0 ? 0 : 1)
}

