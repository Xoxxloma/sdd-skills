console.log('')
console.log('СХЛОПЫВАНИЕ ОСЕЙ:')
console.log(`  ${avg('axRepeat')}  пунктов про повтор и двойное нажатие (во входе таких вопросов 6)`)
console.log(`  ${avg('axConfirm')}  пунктов про подтверждение (во входе 4)`)
console.log('')
