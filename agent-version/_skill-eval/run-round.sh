#!/usr/bin/env bash
# run-round.sh <папка-раунда> <параллельность> <проба...> — прогнать несколько плеч подряд.
#
# Отдельный файл, а не строка в истории команд: раунд запускается не один раз, а после каждой
# правки, и список плеч должен быть предъявим. Плечи идут ПОСЛЕДОВАТЕЛЬНО — параллельно
# запускать их нельзя, пока песочницы лежат в репозитории: два плеча борются за одни и те же
# фикстуры, а сбежавший прогон одного портит засев другого.

set -u
ROUND="${1:-}"
CONC="${2:-5}"
shift 2 || true
[ -n "$ROUND" ] && [ $# -gt 0 ] || { echo "usage: ./run-round.sh <папка-раунда> <параллельность> <проба...>"; exit 1; }
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

for p in "$@"; do
  echo "##### $p"
  bash "$HERE/run-ctx.sh" "$p" "$ROUND" 10 "$CONC" 2>&1 | tail -3
done
echo "РАУНД ГОТОВ: $ROUND"
