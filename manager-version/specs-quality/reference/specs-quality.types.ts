/**
 * Типизация выхода specs-quality: формат specs-quality/5.
 * Итог: <имя документа>.quality.json рядом с документом — один документ, БТ или спека.
 * Источник правды — specs-quality.schema.json и contract.py; этот файл — их описание для чтения.
 *
 * Сводку по автору собирает дашборд из файлов его документов, суммами, а не средними процентов:
 *   качество = Σ sum / Σ max × 100 по оценённым документам одного вида (у документов разный max);
 *   форма = Σ (разделов − form_missing.length) / Σ разделов по документам с form_missing ≠ null (16 у БТ, 23 у спеки);
 *   по критерию = Σ баллов / Σ весов по документам, где он не null.
 */

/** Корень выхода. */
export interface SpecsQualityResult {
  schema: "specs-quality/5";        // версия формата
  generated_at: string;             // когда собран, ISO 8601 с поясом
  params: Params;                   // с какими порогами и весами считали — для вида этого документа
  document: Document;               // сам документ
}

export interface Params {
  below_pct: number;                // порог «низкий итог»: pct ниже — причина below_pct (сейчас 50)
  form_min_missing: number;         // с какого числа пропущенных разделов «не по форме» (сейчас у БТ 5, у спеки 6)
  weights: WeightsBt | WeightsSpec; // вес каждого критерия рубрики этого вида
}

export interface WeightsBt { goal: number; entities: number; functional: number; acceptance: number; roles: number }            // сейчас 0.5, 1, 1, 1, 1
export interface WeightsSpec { source_logic: number; data_model: number; access: number; services: number; contracts: number } // сейчас все 1

/**
 * Документ — одно из трёх: оценка не состоялась; оценённые БТ; оценённая спека.
 * Различать по полям scored и kind: if (!d.scored) … else if (d.kind === "bt") … else …
 */
export type Document = SkippedDocument | ScoredBt | ScoredSpec;

/** Поля, которые есть у любого документа. */
export interface DocumentBase {
  path: string;                     // путь от корня репо: "coddoc/PRJ-101/technical_specification.md"
  repo: string | null;              // репозиторий, если передали при запуске; null — не передали
  kind:
    | "bt"                          // бизнес-требования (business_requirements.md)
    | "spec";                       // техническая спецификация (technical_specification.md)
  key: string;                      // ключ задачи из шапки; нет — имя папки; у узла-фундамента — имя папки эпика
  feature: string | null;           // название фичи из заголовка документа
  author: string | null;            // строка «Автор» из шапки; нет — null
  source: string | null;            // у спеки — документ сверху: путь к БТ, баг-репорту или запросу на правку;
                                    //   null — спека без документа сверху или узел-фундамент; у БТ — всегда null
}

/** Оценка не состоялась: модель не ответила или ответила не по форме. Баллов нет. */
export interface SkippedDocument extends DocumentBase {
  scored: false;
  skip_reason: string;              // «нет ответа модели», «ответ не по схеме: …», «нет критерия data_model»
}

/** Поля оценённого документа любого вида. */
export interface ScoredCommon {
  scored: true;
  pct: number | null;               // итог: sum / max × 100, целое; null — все критерии «н/п»
  sum: number;                      // сумма баллов
  max: number;                      // сумма весов критериев, кроме «н/п»
  attention: AttentionReason[];     // почему документ требует внимания; пусто — не требует
  template: boolean;                // true — «заполнено шаблонно»: ни одного факта предметной области (у БТ)
                                    //   или конкретного имени (у спеки), только общие слова
  form_missing: number[] | null;    // номера разделов шаблона без своего заголовка (списки ниже); null — форму не проверили
  form_pct: number | null;          // доля разделов на месте: (всего − пропущено) / всего × 100; null — форму не проверили
  findings: Finding[];              // по строке на каждый сниженный или «н/п» критерий, по порядку рубрики
}

/** Оценённые бизнес-требования. */
export interface ScoredBt extends DocumentBase, ScoredCommon {
  kind: "bt";
  source: null;
  criteria: CriteriaBt;             // критерий → балл, по порядку рубрики
  origin: null;                     // происхождение у БТ не оценивается
  code_signs: null;                 // признаки кода у БТ не ищутся
}

/** Оценённая техническая спецификация. */
export interface ScoredSpec extends DocumentBase, ScoredCommon {
  kind: "spec";
  criteria: CriteriaSpec;           // критерий → балл, по порядку рубрики
  origin: Origin;                   // как спека появилась
  code_signs: CodeSign[];           // признаки кода — доказательства для origin; [] — признаков нет
}

/** Балл критерия: 0, половина веса или вес. null — «не применимо» (н/п), причина в findings. */
export type Score = number | null;

export interface CriteriaBt {
  goal: Score;                      // «Цель»: понятно, кто, какой результат и зачем (вес 0.5 → баллы 0 / 0.25 / 0.5)
  entities: Score;                  // «Бизнес-сущности»: с какими объектами работает фича, какие новые, что меняется в существующих
  functional: Score;                // «Функционал»: по каждой функции понятно, что она делает и для кого
  acceptance: Score;                // «Критерии приёмки»: у каждого FR проверяемый критерий — условие и наблюдаемый результат
  roles: Score;                     // «Роли и права»: у каждого действия понятно, кто его выполняет
}

export interface CriteriaSpec {
  source_logic: Score;              // «Функционал из источника»: у каждого требования из документа сверху есть реализация в спеке
  data_model: Score;                // «Модель данных и миграции»: сущности с полями, что новое, что меняется, нужна ли миграция
  access: Score;                    // «Роли RBAC/ABAC»: кто вправе выполнить действие и что проверка стоит на сервере
  services: Score;                  // «Изменения и затронутые сервисы»: какие сервисы задеты и что в каждом меняется
  contracts: Score;                 // «Контракты»: у взаимодействий есть метод и путь (или событие), поля с типами, пример, ошибки
}

export type CriterionBt = keyof CriteriaBt;
export type CriterionSpec = keyof CriteriaSpec;

export type AttentionReason =
  | "below_pct"   // итог pct ниже params.below_pct (50 %)
  | "zero"        // хотя бы один критерий получил 0 — чего-то важного нет совсем
  | "template"    // заполнено шаблонно (template = true)
  | "off_form";   // не по шаблону: пропущено разделов не меньше params.form_min_missing (БТ — 5 из 16, спека — 6 из 23)
                  // «по коду» причиной подсветки не считается — это поле origin

export type Origin =
  | "by_code"       // написана по уже готовому коду: два разных признака кода, и среди них «уже сделано» (1, 3 или 6)
  | "skill"         // написана скиллом фреймворка, форма цела
  | "skill_edited"  // скиллом, потом правлена руками: формы нет, но следы скилла остались
  | "outside";      // мимо фреймворка: ни формы, ни следов скилла

export interface CodeSign {
  n: 1 | 2 | 3 | 4 | 5 | 6;         // номер признака из рубрики спеки
  kind:                             // то же словами
    | "сделано в коде"                 // 1 — правка описана в прошедшем времени: «добавлен метод», «реализовано в ветке…»
    | "путь к исходнику"               // 2 — путь или имя файла исходников: src/main/…, EstimateServiceImpl.java
    | "объём правки в строках"         // 3 — «+120 строк», «удалено 40 строк»
    | "рефакторинг или тесты"          // 4 — рефакторинг, переименования, добавленные тесты пунктами изменений
    | "миграция или changelog"         // 5 — точное имя файла миграции или changelog с версией
    | "закрытое изменение источником"; // 6 — источником назван смёрженный PR, коммит, архив изменений
  quote: string;                    // цитата из спеки
  quote_found?: false;              // есть, только если цитаты нет в тексте документа
}

export interface Finding {
  criterion: CriterionBt | CriterionSpec; // какой критерий снижен или «н/п»
  comment: string | null;           // что не так или почему «н/п»; где искали — в скобках: «(искал: Авторизация/доступ на бэке)»
  fix: string | null;               // что подняло бы балл; у «н/п» обычно null
  quote: string | null;             // раздел и цитата: "§4.4: «кнопка видна согласующему»"; null — цитировать нечего («не найдено»)
  quote_found?: false;              // есть, только если цитаты нет в тексте документа; балл от этого не меняется
}

