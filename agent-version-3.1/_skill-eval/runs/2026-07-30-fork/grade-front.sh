#!/usr/bin/env bash
# Грейдер тира A на фикстуре SM-FRONT: ветвление формы по типу, порядок секций, версии, объём.
set -uo pipefail
F="${1:?дай файл с ответом}"
pass=0; fail=0
ok()  { printf '  ok   %s\n' "$1"; pass=$((pass+1)); }
bad() { printf '  FAIL %s — %s\n' "$1" "$2"; fail=$((fail+1)); }

echo "SM-3 ветвление формы: секции фронта есть, секции бэкенда отсутствуют"
for s in 'Экраны' 'Потребляемые API' 'Состояние и данные'; do
  grep -q "^## $s" "$F" && ok "есть «$s»" || bad "«$s»" "секции нет"
done
for s in 'Публичный контракт' 'Владеет данными' 'События'; do
  grep -q "^## $s" "$F" && bad "«$s»" "секция чужого типа выведена" || ok "нет «$s»"
done

echo "SM-10 порядок секций совпадает с колонкой frontend"
got=$(awk '/^## Назначение/{f=1} f' "$F" | grep '^## ' | sed 's/^## //' | grep -v '^Заметки команды$' | tr '
' '/')
want='Назначение/Что умеет для пользователя/Стек/Экраны/Потребляемые API/Состояние и данные/Зависит от/Кто меня потребляет/Роли и доступ/'
[ "$got" = "$want" ] && ok "порядок секций" || bad "порядок секций" "получено: $got"

echo "SM-28 контроль масштаба: все пять роутов"
n=0
for r in '/incidents' '/incidents/:id' '/incidents/:id/assign' '/coverage' '/settings/notifications'; do
  grep -q -- "$r" "$F" && n=$((n+1)) || bad "роут $r" "не доехал"
done
[ "$n" = "5" ] && ok "роутов 5 из 5"

echo "SM-6 версии"
grep -qE 'React 18|React Router 6|\^18\.|\^6\.|5\.0\.|vite [0-9]|zustand [0-9]' "$F" && bad "версии" "номера в «Стеке»" || ok "версий нет"

echo "SM-11 имена сервисов из манифеста"
grep -qE 'geo-service|auth-service|incident-api-service' "$F" && bad "имя из пути" "вместо name из манифеста" || ok "имён из путей нет"

echo "SM-5 роли не выдуманы (роль приходит из хост-приложения)"
grep -q '^## Роли и доступ' "$F" && ok "секция ролей есть" || bad "секция ролей" "отсутствует"

echo "SM-43 / SM-47 секции без источника"
grep -q '^## Заметки команды' "$F" && bad "секция notes" "субагент её вывел" || ok "секции notes нет"
mirrors=$(awk '/^## Кто меня потребляет/{f=1;next} f && /^## /{f=0} f' "$F" | grep -cE '^[|] *`?[a-z]')
[ "$mirrors" = "0" ] && ok "«Кто меня потребляет» пустой формой" || bad "выдумано зеркал: $mirrors" "источника нет"

echo "SM-9 аббревиатуры"
grep -qi 'частное охранное\|чрезвычайно опасн' "$F" && bad "ЧОП" "расшифрован, чего в коде нет" || ok "ЧОП не расшифрован"

echo
printf 'ИТОГО %s: ok %s, FAIL %s\n' "$(basename "$F")" "$pass" "$fail"
