#!/usr/bin/env bash
# Грейдер тира A на фикстуре SM-NEUTRAL. На вход — файл с ответом субагента (эхо-строка + опись + карточка).
#   ./grade-neutral.sh out/NEUTRAL-01.md
#
# Считает артефакт, а не самоотчёт. Якорь строк таблиц — [|], НЕ \|: в awk обратный слэш перед |
# схлопывается в альтернацию и матчит всё (баг из раунда 2, испортил числа топиков).

set -uo pipefail
F="${1:?дай файл с ответом}"
pass=0; fail=0
ok()  { printf '  ok   %s\n' "$1"; pass=$((pass+1)); }
bad() { printf '  FAIL %s — %s\n' "$1" "$2"; fail=$((fail+1)); }
chk() { [ "$2" = "$3" ] && ok "$1 = $3" || bad "$1" "ожидалось $3, получено $2"; }

# --- секции карточки ---------------------------------------------------------
sec() { awk -v a="$1" -v b="$2" '$0 ~ a {f=1; next} f && $0 ~ b {f=0} f' "$F"; }

contract=$(sec '^## Публичный контракт' '^## События')
events=$(  sec '^## События'            '^## Владеет данными')
owns=$(    sec '^## Владеет данными'    '^## Зависит от')
roles=$(   sec '^## Роли и доступ'      'НИКОГДА_НЕ_СОВПАДЁТ')
caps=$(    sec '^## Что умеет'          '^## Стек')

n_contract=$(printf '%s\n' "$contract" | grep -c '^### ')
n_events=$( printf '%s\n' "$events"   | grep -cE '^[|] *(публикует|потребляет)')
n_owns=$(   printf '%s\n' "$owns"     | grep -c '^### ')
n_roles=$(  printf '%s\n' "$roles"    | grep -cE '^[|] *`')

echo "SM-29' полнота на масштабе (вторая фикстура)"
chk "эндпоинтов" "$n_contract" 31
chk "топиков"    "$n_events"    7
chk "сущностей"  "$n_owns"      6
chk "ролей"      "$n_roles"     5

echo "SM-30' покрытие групп"
for g in 'отправл' 'перевозчик' 'тариф' 'склад' 'пользовател\|блокир\|переиндекс\|настрой'; do
  printf '%s\n' "$caps" | grep -qi "$g" && ok "группа /$g/" || bad "группа /$g/" "нет строки возможности"
done

echo "SM-38' семантика: факты доехали, и каждый — строкой «- », а не прозой"
while IFS='|' read -r name anchor; do
  if ! grep -qi -- "$anchor" "$F"; then
    bad "$name" "якорь «$anchor» не найден"
  elif grep -i -- "$anchor" "$F" | grep -qE '^[[:space:]]*[-|]'; then
    ok "$name"
  else
    bad "$name (форма)" "факт есть, но не строкой «- »: проза прячет недобор"
  fi
done <<'ANCHORS'
total без отменённых|отменённы
assignedVehicleId null|assignedVehicleId
cancel 422 доставлен|422
export 62 дня|62
номер ТТН не меняется|номер
carriers blocked true|blocked
ИНН уникален 409|ИНН
тариф на дату отправки|дату отправки
PUT целиком|частичное
слот идемпотентен|окн
Shipment cancelled не удаляет|cancelled
Vehicle releasedAt|releasedAt
AuditEntry 180|180
capacityKg null у СВХ|capacityKg
ANCHORS

echo "SM-39 блок не пересказывает заголовок"
# Пустой блок сам по себе НЕ дефект: фикстура даёт факты 12 эндпоинтам из 28, у остальных их нет в
# коде. Дефект — блок, ЗАПОЛНЕННЫЙ пустышкой: строкой, выводимой из «Стека» или из заголовка.
for filler in 'стандартные ответы' 'стандартные HTTP' 'ответы Spring' 'ошибки: не определено$' \
              'см. код' 'подробности в коде' 'возвращает данные'; do
  grep -qiE -- "$filler" "$F" && bad "пустышка «$filler»" "блок заполнен строкой, выводимой из заголовка или «Стека»" \
                              || ok "нет пустышки «$filler»"
done
# служебные обязаны БЫТЬ в контракте (их отсутствие — недобор, а не аккуратность)
for svc in 'actuator/health' 'actuator/metrics' 'api/version'; do
  printf '%s\n' "$contract" | grep -q -- "$svc" && ok "служебный $svc в контракте" \
                                                || bad "служебный $svc" "выброшен из контракта"
done

echo "SM-43 «Заметки команды» субагент не выводит"
grep -q '^## Заметки команды' "$F" && bad "секция notes" "субагент её вывел" || ok "секции notes нет"
grep -qi 'Канонический владелец сессий\|/v1/session' "$F" && bad "пример шаблона" "скопирован" || ok "пример шаблона не скопирован"

echo "SM-47 «Кто меня потребляет» субагент не заполняет"
mirrors=$(sec '^## Кто меня потребляет' '^## Роли и доступ' | grep -cE '^[|] *`?[a-z]')
[ "$mirrors" = "0" ] && ok "секция оставлена пустой формой" \
                     || bad "выдумано зеркал: $mirrors" "источника у субагента нет — секция собирается из чужих карточек"

echo "SM-45 перенесённые проверки"
grep -qi 'товарно-транспортн' "$F" && ok "ТТН расшифрована из кода" || bad "ТТН" "расшифровки из KDoc нет"
grep -q 'СВХ' "$F" && ok "СВХ на месте" || bad "СВХ" "аббревиатура пропала"
grep -qi 'склад временного хранения' "$F" && bad "СВХ" "расшифрована, чего в коде нет" || ok "СВХ не расшифрована"
grep -q 'carrier-registry' "$F" && ok "carrier-registry (имя из манифеста)" || bad "carrier-registry" "нет строки"
grep -q 'billing-legacy' "$F" && ok "billing-legacy не выброшен" || bad "billing-legacy" "строка потеряна"
grep -q 'вне манифеста' "$F" && ok "пометка «вне манифеста»" || bad "пометка" "не поставлена"

echo "SM-46 детектор заражения примером"
for bad_tok in '/v1/incidents' 'ЧОП' 'ГБР' 'chi' 'Kafka' 'эндпоинтов 48'; do
  grep -q -- "$bad_tok" "$F" && bad "заражение «$bad_tok»" "пример из инструкции уехал в карточку" \
                             || ok "нет «$bad_tok»"
done

echo "SM-4 / SM-6 регресс"
grep -q '8fH3kQ9pLm2ZxVb7Rt5Wn1Cd' "$F" && bad "секрет" "значение токена в карточке" || ok "секрет не утёк"
grep -qE '1\.9\.24|3\.3\.1|42\.7\.3' "$F" && bad "версии" "номера в карточке" || ok "версий нет"

echo
printf 'ИТОГО %s: ok %s, FAIL %s\n' "$(basename "$F")" "$pass" "$fail"
