#!/usr/bin/env bash
# run-pool.sh — гоняет пул прогонов одного скилла на одном промпте.
#
#   ./run-pool.sh <скилл.md> <промпт.txt> <каталог-плеча> <N> [параллельность] [папка-засева]
#
# Каждый прогон живёт в своей песочнице `<каталог-плеча>/run-NN`, она же его рабочая
# директория — поэтому `docs/<KEY>/` скилл собирает внутри неё, а не в репозитории.
#
# ЗАСЕВ. Шестой аргумент — папка, содержимое которой копируется в песочницу ПЕРЕД прогоном.
# Он нужен трём скиллам из четырёх: `task-decomposition-doc` работает по готовому БТ эпика,
# `technical-spec-doc` — по подтверждённому БТ, `stage-breakdown-doc` — по готовой спеке.
# Без засева их промпты ссылаются на файлы, которых в песочнице нет, и прогон меряет не то:
# у пробы «первый ход — только вопросы» главный анкер «спека не написана» выполняется
# автоматически, потому что входного документа не нашлось. Зелёный по неверной причине.
#
# Копия делается НА КАЖДЫЙ прогон, а не одна на пробу. Причина взята из `setup-rv-runs.mjs`,
# где этот механизм уже работает: запрет писать в промпте изоляцией не является, и на прошлом
# замере один агент из двадцати записал результат прямо в фикстуру — в общей песочнице это
# молча испортило бы все последующие прогоны, они читали бы уже изменённый документ.
#
# Что засеяно, перечисляется в `_seeded.txt` внутри песочницы: грейдеры, считающие «сколько
# файлов создал скилл», обязаны вычесть засеянное, иначе вход прогона зачтётся ему в выход.
#
# ПОЧЕМУ ОТВЕТ БЕРЁТСЯ ИЗ stdout, А НЕ ПРОСЬБОЙ «СОХРАНИ answer.md».
# Прошлый круг (runs/2026-08-06-br3) просил агента сохранить свой ответ файлом, и это внесло
# confound прямо в измеряемое: проба спрашивает «создаст ли скилл файл», а стенд сам велел
# создать файл. Здесь `claude -p` печатает финальный ответ в stdout, стенд его перенаправляет,
# и в промпте прогона про запись файлов не сказано НИЧЕГО. Единственные файлы в песочнице —
# те, которые скилл решил создать сам.
#
# Идемпотентность: песочница с непустым answer.md пропускается, поэтому скрипт можно
# перезапускать после обрыва, не теряя и не задваивая прогоны.

set -u

SKILL="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
PROMPT="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"
OUT="$3"
N="$4"
CONC="${5:-5}"
SEED="${6:-}"
# Куда внутри песочницы лечь засеву. Промпты ссылаются на вход по-разному: пробы БТ и
# тех-спеки — как `docs/<КЛЮЧ>/…`, пробы разреза на этапы — как `<КЛЮЧ>/…` от корня. Держать
# под каждую форму отдельную копию фикстуры значит завести второй источник правды, который
# разъедется с первым; проще указать место при вызове.
SEED_AT="${7:-.}"

[ -f "$SKILL" ]  || { echo "нет файла скилла: $SKILL";  exit 1; }
[ -f "$PROMPT" ] || { echo "нет файла промпта: $PROMPT"; exit 1; }
if [ -n "$SEED" ]; then
  [ -d "$SEED" ] || { echo "нет папки засева: $SEED"; exit 1; }
  SEED="$(cd "$SEED" && pwd)"
fi
mkdir -p "$OUT"

run_one() {
  local i="$1"
  local sb="$OUT/run-$i"
  mkdir -p "$sb"
  if [ -s "$sb/answer.md" ]; then echo "  run-$i — уже есть, пропуск"; return 0; fi
  local abs_sb
  abs_sb="$(cd "$sb" && pwd)"

  # Засев ДО прогона и только в свежую песочницу: при перезапуске после обрыва песочница с
  # готовым ответом уже отсеяна выше, а песочница без ответа засевается заново — прогон
  # начинается с того же состояния диска, что и в первый раз.
  if [ -n "$SEED" ]; then
    mkdir -p "$abs_sb/$SEED_AT"
    cp -r "$SEED"/. "$abs_sb/$SEED_AT"/ 2>/dev/null
    ( cd "$abs_sb" && find . -type f -not -name '_seeded.txt' | sed 's|^\./||' | sort ) > "$abs_sb/_seeded.txt"
  fi
  local task="Твоя рабочая директория — ${abs_sb}. Считай её корнем рабочего репозитория. Ничего за её пределами не создавай и не изменяй: путь, ведущий наружу, — ошибка сборки пути, а не повод писать туда.

Прочитай целиком файл ${SKILL} — это скилл. Дальше действуй строго по нему, как если бы он был загружен командой /skill.

Интерактивного инструмента вопросов (AskUserQuestion) в этом окружении нет. Если по скиллу нужно задать вопросы — задавай их обычным текстом.

Сообщение пользователя лежит в файле ${PROMPT}. Прочитай его и ответь на него по скиллу. Твой ответ — то, что ты сказал бы пользователю в чат."

  ( cd "$sb" && timeout 900 claude -p "$task" --model haiku --permission-mode bypassPermissions ) \
      > "$sb/answer.md" 2> "$sb/_stderr.log"
  local rc=$?

  # ОТКАЗ РАННЕРА НАДО ОТЛИЧАТЬ ОТ ОТВЕТА МОДЕЛИ, И ПО РАЗМЕРУ ЭТО НЕ ВИДНО.
  # Круг 2026-08-06 упёрся в лимит API: `claude -p` напечатал в stdout «API Error: 403
  # Request not allowed / Please run /login», раннер увидел непустой answer.md и зачёл
  # 68 прогонов из 180 как состоявшиеся. Грейдер потом честно грейдил текст ошибки.
  # Проверка «непустой файл» для этого класса бесполезна — нужен разбор содержимого.
  # Круг 2026-08-07 добавил в этот список лимит СЕССИИ: `claude -p` печатает «You've hit
  # your session limit · resets 5am», 56 байт, и прежний список его не ловил. Цена ровно
  # та же, что в прошлый раз, только хуже: в `runs/2026-08-07-round2/br3-D` отравлены были
  # ВСЕ 20 прогонов, грейдер честно напечатал «Измерено: 20 из 20, файл записан 0 из 20» —
  # идеальный ложный красный на главном анкере пробы. Правило прежнее: отказ раннера
  # обязан выпадать в «не измерено», а не в «провалено».
  if grep -qiE "API Error|Request not allowed|Please run /login|Credit balance|rate limit|session limit|usage limit" "$sb/answer.md" 2>/dev/null; then
    mv "$sb/answer.md" "$sb/_api-failure.txt"
    echo "  run-$i — ОТКАЗ API, песочница помечена и в счёт не идёт"
    return 0
  fi
  if [ $rc -ne 0 ] || [ ! -s "$sb/answer.md" ]; then
    echo "  run-$i — ОТКАЗ (rc=$rc), см. $sb/_stderr.log"
  else
    echo "  run-$i — готов"
  fi
}

echo "плечо: $OUT"
echo "скилл: $SKILL"
echo "промпт: $PROMPT"
echo "прогонов: $N, параллельно: $CONC"

running=0
for i in $(seq -w 1 "$N"); do
  run_one "$i" &
  running=$((running + 1))
  if [ "$running" -ge "$CONC" ]; then wait -n 2>/dev/null || wait; running=$((running - 1)); fi
done
wait

echo "ГОТОВО: $OUT — песочниц с ответом: $(find "$OUT" -name answer.md -size +0 | wc -l) из $N"
