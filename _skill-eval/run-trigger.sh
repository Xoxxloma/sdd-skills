#!/usr/bin/env bash
# run-trigger.sh — пул прогонов для замера АВТОСРАБАТЫВАНИЯ приёмки внутри пайплайна.
#
#   ./run-trigger.sh <скилл-автора.md> <промпт.txt> <каталог-плеча> <N> [параллельность] [засев]
#
# Отличие от run-pool.sh — два, и оба обязательны для этой пробы.
#
# 1. В песочницу засеваются ВСЕ под-скиллы петли (`.claude/skills/`) — они становятся
#    НАСТОЯЩИМИ скиллами в реестре, а не файлами по пути. Иначе мерить нечего: модель не
#    может вызвать то, чего в реестре нет, а не найдя под-скилл — делает его работу сама.
#    Список и обоснование — у переменной SUBSKILLS ниже. Скилл автора по-прежнему грузится
#    ПУТЁМ — так меряют все прежние раунды, и менять способ ради этой пробы нельзя.
#
# 2. Ответ пишется потоком (`--output-format stream-json`), а не текстом. Факт вызова скилла
#    и факт запуска субагента в финальном тексте не видны: агент может о них рассказать, не
#    сделав, и наоборот. Правило репы «грейдить файл, а не формулировку отчёта» здесь
#    означает «грейдить поток вызовов, а не пересказ».
#
# Идемпотентность как в run-pool.sh: песочница с непустым stream.jsonl пропускается.

set -u

SKILL="$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
PROMPT="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"
OUT="$3"
N="$4"
CONC="${5:-5}"
SEED="${6:-}"

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SKILLS_SRC="$REPO/agent-version-3.2"

# В реестр песочницы кладутся ВСЕ под-скиллы петли, а не одна приёмка.
#
# До 2026-08-09 сюда попадал только `spec-review`. Последствий было два, и оба портили замер,
# а не скилл: (1) передачу контекста в под-скиллы нельзя было измерить в принципе — 8 прогонов
# из 10 упирались в отсутствующий `technical-spec-doc` и до неё не доходили; (2) прогон, не
# найдя под-скилл, делал его работу сам и писал документ — пункт «оркестратор сам файлов не
# пишет» краснел не про скилл. Один такой прогон вдобавок записал файлы за пределы песочницы.
#
# `analyst-workspace` СЮДА НЕ КЛАДЁТСЯ: скилл автора грузится ПУТЁМ, так меряют все прежние
# раунды, и менять способ загрузки ради этого нельзя. `service-map` и `archive-spec` тоже нет —
# они читают код соседних сервисов, которого в песочнице не существует.
SUBSKILLS="spec-review business-requirements-doc task-decomposition-doc technical-spec-doc stage-breakdown-doc project-conventions domain-glossary"

[ -f "$SKILL" ]  || { echo "нет файла скилла: $SKILL";  exit 1; }
[ -f "$PROMPT" ] || { echo "нет файла промпта: $PROMPT"; exit 1; }
for s in $SUBSKILLS; do
  [ -d "$SKILLS_SRC/$s" ] || { echo "нет под-скилла: $SKILLS_SRC/$s"; exit 1; }
done
if [ -n "$SEED" ]; then
  [ -d "$SEED" ] || { echo "нет папки засева: $SEED"; exit 1; }
  SEED="$(cd "$SEED" && pwd)"
fi
mkdir -p "$OUT"

run_one() {
  local i="$1"
  local sb="$OUT/run-$i"
  # Стоп-файл пула. Снять обёртку недостаточно: осиротевший драйвер продолжает плодить
  # песочницы (2026-08-07: children доехал до 13 вместо 8, пришлось убивать по PID).
  # `touch <плечо>/_STOP` — и все ещё не стартовавшие прогоны выпадают в «не измерено».
  if [ -e "$OUT/_STOP" ]; then echo "  run-$i — СТОП-ФАЙЛ, прогон не запускался"; return 0; fi
  mkdir -p "$sb"
  # Пропускаем только ДОЕХАВШИЙ прогон. Помеченный недоехавшим переигрывается: правило репы
  # «прогон, выглядящий провалом на середине, дописывается до успеха».
  if [ -s "$sb/stream.jsonl" ] && [ ! -e "$sb/_incomplete.txt" ]; then
    echo "  run-$i — уже есть, пропуск"; return 0
  fi
  # Метки прошлой попытки снимаем ПЕРЕД перезапуском. Иначе переигранный успешно прогон
  # остаётся с чужим `_api-failure.txt` и молча выпадает из грейда — плечо недосчитывается
  # ровно на те прогоны, которые дописали до успеха.
  rm -f "$sb/stream.jsonl" "$sb/_incomplete.txt" "$sb/_api-failure.txt" "$sb/_escaped.txt"
  local abs_sb
  abs_sb="$(cd "$sb" && pwd)"

  # Под-скиллы — в реестр скиллов песочницы. Копия на каждый прогон: общая папка означала бы,
  # что прогон, решивший что-нибудь в ней записать, молча испортит все последующие.
  mkdir -p "$abs_sb/.claude/skills"
  for s in $SUBSKILLS; do cp -r "$SKILLS_SRC/$s" "$abs_sb/.claude/skills/" 2>/dev/null; done

  if [ -n "$SEED" ]; then
    cp -r "$SEED"/. "$abs_sb"/ 2>/dev/null
  fi
  ( cd "$abs_sb" && find . -type f -not -name '_seeded.txt' | sed 's|^\./||' | sort ) > "$abs_sb/_seeded.txt"

  local task="Твоя рабочая директория — ${abs_sb}. Считай её корнем рабочего репозитория. Ничего за её пределами не создавай и не изменяй: путь, ведущий наружу, — ошибка сборки пути, а не повод писать туда.

Прочитай целиком файл ${SKILL} — это скилл. Дальше действуй строго по нему, как если бы он был загружен командой /skill.

Интерактивного инструмента вопросов (AskUserQuestion) в этом окружении нет. Если по скиллу нужно задать вопросы — задавай их обычным текстом.

Сообщение пользователя лежит в файле ${PROMPT}. Прочитай его и ответь на него по скиллу. Твой ответ — то, что ты сказал бы пользователю в чат."

  # CLAUDE_CODE_PRINT_BG_WAIT_CEILING_MS=0 — ждать субагентов сколько нужно.
  # По умолчанию CLI ждёт фоновые задачи 600 с и обрывает ход («Background tasks still
  # running after 600s; terminating»). Приёмка поднимает субагентов ИМЕННО фоновой задачей,
  # и на трёх детях по очереди (ПРАВКА 1) 600 с не хватает: ход обрывается на третьем
  # ребёнке, а в потоке при этом уже лежат `result` завершившихся субагентов — то есть
  # оборванный прогон проходит проверку вытопки «есть терминальный result» и грейдится
  # как провал скилла. Границу держит `timeout` ниже, а не потолок ожидания.
  ( cd "$sb" && CLAUDE_CODE_PRINT_BG_WAIT_CEILING_MS=0 timeout 2400 claude -p "$task" --model haiku --permission-mode bypassPermissions \
      --output-format stream-json --verbose ) \
      > "$sb/stream.jsonl" 2> "$sb/_stderr.log"
  local rc=$?

  # Отказ раннера обязан выпадать в «не измерено», а не в «провалено» — правило репы,
  # оплаченное дважды (2026-08-06: 68 прогонов из 180; 2026-08-07: 20 из 20).
  if grep -qiE "API Error|Request not allowed|Please run /login|Credit balance|rate limit|session limit|usage limit" "$sb/stream.jsonl" 2>/dev/null; then
    mv "$sb/stream.jsonl" "$sb/_api-failure.txt"
    echo "  run-$i — ОТКАЗ API, песочница помечена и в счёт не идёт"
    return 0
  fi
  # ПРОГОН, ВЫШЕДШИЙ ЗА ПЕСОЧНИЦУ, — ОТКАЗ СТЕНДА, А НЕ НАРУШЕНИЕ СКИЛЛА.
  # 2026-08-08: `readybt-p4/run-11` не нашёл `task-decomposition-doc` в реестре, сделал разрез
  # сам и записал три детских БТ по абсолютным путям в `_skill-eval/fixtures/`. Это испорченный
  # вход для всех последующих плеч и негодное измерение для этого. Такой прогон обязан выпадать
  # в «не измерено» — по тому же правилу, что и отказ API, — и переигрываться.
  # Разбор ТОЛЬКО через JSON: `Read` тоже несёт `file_path`, и проверка регуляркой по сырому
  # потоку пометила бы каждый прогон. Смотрим лишь пишущие вызовы.
  node "$REPO/_skill-eval/check-escape.mjs" "$abs_sb" || true

  # НЕДОЕХАВШИЙ ПРОГОН ПОМЕЧАЕТСЯ ЗДЕСЬ, а не угадывается потом по содержимому потока.
  # Два признака, и оба видны только раннеру: ненулевой код возврата (сработал `timeout`)
  # и нотис CLI об обрыве фоновых задач. Без метки такой прогон снаружи неотличим от
  # честного провала скилла — правило репы «отказ раннера обязан выпадать в „не измерено“».
  if [ $rc -ne 0 ] || [ ! -s "$sb/stream.jsonl" ] \
     || grep -q "Background tasks still running" "$sb/_stderr.log" 2>/dev/null; then
    echo "недоехал: rc=$rc" > "$sb/_incomplete.txt"
    cat "$sb/_stderr.log" >> "$sb/_incomplete.txt" 2>/dev/null
    echo "  run-$i — НЕДОЕХАЛ (rc=$rc), помечен, в счёт не идёт"
  else
    rm -f "$sb/_incomplete.txt"
    echo "  run-$i — готов"
  fi
}

echo "плечо: $OUT"
echo "скилл автора: $SKILL"
echo "промпт: $PROMPT"
echo "в реестр песочницы: $SUBSKILLS"
echo "прогонов: $N, параллельно: $CONC"

running=0
for i in $(seq -w 1 "$N"); do
  run_one "$i" &
  running=$((running + 1))
  if [ "$running" -ge "$CONC" ]; then wait -n 2>/dev/null || wait; running=$((running - 1)); fi
done
wait

echo "ГОТОВО: $OUT — песочниц с потоком: $(find "$OUT" -name stream.jsonl -size +0 | wc -l) из $N"
