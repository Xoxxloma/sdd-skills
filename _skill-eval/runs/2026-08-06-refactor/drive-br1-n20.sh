#!/usr/bin/env bash
# BR-1 до N=20 на обоих плечах.
#
# Повод: в круге на N=10 BR-1 в строгом чтении дала 8 (вариант A) против 5 (вариант B) —
# единственное заметное расхождение круга, и оно в сторону старой версии. Точный тест Фишера
# даёт p ≈ 0.35, то есть на десяти наблюдениях это неотличимо от случайного. Репа знает этот
# урок трижды: «N=10 не различает правки», а промежуточный срез на десяти однажды прочитался
# как «дефект 1/10, шум» там, где на двадцати было 5/20.
#
# Раннер идемпотентен: первые десять песочниц каждого плеча уже заполнены и пропускаются,
# добираются только run-11…run-20.
#
# Параллельность 3 — на десяти одновременных процессах круг упёрся в лимит API.

set -u
cd "$(dirname "$0")/../../.." || exit 1
ROOT="_skill-eval/runs/2026-08-06-refactor"

for arm in A B; do
  echo "############ BR-1 до N=20 / вариант-$arm ############"
  bash _skill-eval/run-pool.sh \
    "$ROOT/_arms/variant-$arm.md" \
    "_skill-eval/fixtures/br1-prompt.txt" \
    "$ROOT/br1-$arm" \
    20 3
done

echo
for arm in A B; do
  d="$ROOT/br1-$arm"
  printf "br1 вариант-%s: ответов %s, отказов API %s\n" "$arm" \
    "$(find "$d" -name answer.md -size +0 | wc -l)" \
    "$(find "$d" -name _api-failure.txt 2>/dev/null | wc -l)"
done
