#!/usr/bin/env bash
# Круг 3 (2026-08-07) — изолирует правки «снятие разночтений» от чужой правки счётчика.
#
# ПЛЕЧИ. variant-D (742 строки) = состояние ровно ПЕРЕД правками разночтений; в нём уже
# есть счётчик `❓ осталось: N` из круга 2. variant-E (750) = D + 12 правок. Разница между
# плечами — только разночтения, и это единственное, что круг меряет.
#
# ПОЧЕМУ ПЛЕЧО «ДО» ГОНЯЕТСЯ ЗАНОВО, А НЕ БЕРЁТСЯ ИЗ runs/2026-08-06-br3.
# Тот круг снят прежним стендом, который просил агента сохранить ответ файлом, — в пробе,
# которая спрашивает «создаст ли скилл файл». Confound снят переделкой раннера, но старые
# числа с новыми несравнимы: 16 из 20 оттуда — это верхняя оценка, а не база.
#
# У br4/br1 плечо «до» не гоняется сознательно: там анкер обратный («файла НЕТ»), и прежний
# стенд смещал результат в сторону записи, то есть старые 10/10 — консервативная оценка.
# Их цель здесь — контроль: правка двигает скилл К записи, и ломаться будет именно тут.

set -u
cd "$(dirname "$0")/../.." || exit 1
R=runs/2026-08-07-round3
A=$R/_arms

./run-pool.sh "$A/variant-D.md" fixtures/br3-prompt.txt "$R/br3-D" 20 5
./run-pool.sh "$A/variant-E.md" fixtures/br3-prompt.txt "$R/br3-E" 20 5
./run-pool.sh "$A/variant-E.md" fixtures/br4-prompt.txt "$R/br4-E" 10 5
./run-pool.sh "$A/variant-E.md" fixtures/br1-prompt.txt "$R/br1-E" 10 5

echo "=== ПУЛ ЗАКОНЧЕН. Грейдить только сейчас, не раньше."
for d in br3-D br3-E br4-E br1-E; do
  echo "$d: ответов $(find "$R/$d" -name answer.md -size +0 2>/dev/null | wc -l), отказов API $(find "$R/$d" -name _api-failure.txt 2>/dev/null | wc -l)"
done
