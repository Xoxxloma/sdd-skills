#!/usr/bin/env bash
# Круг 2. Мерится ОДНА правка: реестр гейтов заканчивается строкой «❓ осталось: N», и
# переход «писать / спрашивать» стал арифметикой по N вместо ощущения готовности.
#
#   variant-C — плечо B круга 1 (720 строк), без правки
#   variant-D — то же + правка (742)
#
# Повод — измеренный дефект круга 1: 12 из 40 write-прогонов не записали файл при чистом
# реестре, форма во всех восьми разобранных случаях одна («карта понимания + всё верно?»).
# Правило против этого в скилле было и игнорировалось; репа знает такой случай — чинится не
# усилением запрета, а тем, что ответ становится числом.
#
# Сетапы выбраны по частоте дефекта в круге 1:
#   bs6 — файла нет у 5/10 (C) — самая большая доля
#   br3 — файла нет у 4/10 (C)
# N=20 на плечо: при базовой доле около 50% десяти наблюдений не хватит (урок репы, трижды).
# Параллельность 4 — на десяти круг 1 упёрся в лимит API.

set -u
cd "$(dirname "$0")/../../.." || exit 1
ROOT="_skill-eval/runs/2026-08-07-round2"

for setup in bs6 br3; do
  for arm in C D; do
    echo "############ $setup / вариант-$arm ############"
    bash _skill-eval/run-pool.sh \
      "$ROOT/_arms/variant-$arm.md" \
      "_skill-eval/fixtures/${setup}-prompt.txt" \
      "$ROOT/$setup-$arm" \
      20 4
  done
done

echo
echo "=========== ИТОГ ==========="
for setup in bs6 br3; do
  for arm in C D; do
    d="$ROOT/$setup-$arm"
    printf "%-4s вариант-%s: ответов %2s, БТ на диске %2s, отказов API %2s\n" "$setup" "$arm" \
      "$(find "$d" -name answer.md -size +0 2>/dev/null | wc -l)" \
      "$(find "$d" -name business_requirements.md 2>/dev/null | wc -l)" \
      "$(find "$d" -name _api-failure.txt 2>/dev/null | wc -l)"
  done
done
