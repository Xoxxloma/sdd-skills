console.log(`синтетические отчёты: ${root}\n`);
const out = execFileSync(process.execPath, [join(here, 'grade-rv.mjs'), root], { encoding: 'utf8' });
const tail = out.slice(out.indexOf('=== СВОДКА'));
console.log(tail);

// Ожидание: у каждой пробы «идеальный» проходит всё, «сломанный» — не всё.
// Значит в сводке каждый пункт обязан быть 1/2 или 2/2, и хотя бы один — 1/2.
const lines = tail.split('\n').filter((l) => /\d+\/2/.test(l));
const zero = lines.filter((l) => /\s0\/2\s/.test(l));
const half = lines.filter((l) => /\s1\/2\s/.test(l));
console.log(`\nпунктов всего: ${lines.length}, различающих (1/2): ${half.length}, нулевых (0/2): ${zero.length}`);
if (zero.length) {
  console.log('!! пункты, красные ДАЖЕ на идеальном отчёте — грейдер сломан:');
  for (const l of zero) console.log(l);
  process.exit(1);
}
if (!half.length) {
  console.log('!! ни один пункт не различает идеальный и сломанный отчёт');
  process.exit(1);
}
