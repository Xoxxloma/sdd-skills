// Самотест грейдера отчётов `grade-rv.mjs`.
//
// Правило репы: грейдер валидируется на заведомо известном результате ДО того, как по нему
// объявят число. Здесь материализуются два синтетических отчёта на каждую пробу — «идеальный»
// (ждём все пункты зелёными) и «сломанный» (ждём красные ровно там, где сломано), — после чего
// по ним гоняется настоящий грейдер.
//
// Сломанные отчёты написаны не «пустышкой», а типовыми ложными срабатываниями: легенда объявлена
// открытой развилкой, законная 🟡 вынесена в перечень, путь достроен из общих знаний. Пустышка
// проверяет только, что грейдер не красит белое; эти — что он видит настоящий брак.
//
// Запуск: node agent-version-3.2/_skill-eval/selftest-rv.mjs

import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, 'selftest', 'rv');
rmSync(root, { recursive: true, force: true });

const put = (evalDir, run, body) => {
  const p = join(root, evalDir, run, 'outputs');
  mkdirSync(p, { recursive: true });
  writeFileSync(join(p, 'report.md'), body, 'utf8');
};

