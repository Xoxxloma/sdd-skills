enum class Role {
    DISPATCHER,          // отправления и назначение машин
    CARRIER_MANAGER,     // справочник перевозчиков и их парк
    TARIFF_EDITOR,       // тарифы и расчёт
    WAREHOUSE_OPERATOR,  // склады и окна приёмки
    ADMIN                // всё, включая переиндексацию
}

