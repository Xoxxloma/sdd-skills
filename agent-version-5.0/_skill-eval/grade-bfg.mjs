#!/usr/bin/env node
// grade-bfg.mjs — пробы bfg-scroll / bfg-role: ЛИШНИЕ ТЕХ-ГЕЙТЫ у багфикса.
//
//   node grade-bfg.mjs <каталог плеча>        # плечо определяется по имени каталога
//   node grade-bfg.mjs <каталог> --arm scroll # либо явно
//   node grade-bfg.mjs --selftest
//
// ЧТО ГРЕЙДИТСЯ. `answer.md` — текстовый ответ прогона (stdout). Оба плеча ВОПРОСНЫЕ: по правилу
// скилла «turn 1 = questions only. No file» законный исход — вопросы и ни одного файла. Поэтому
// артефакт здесь и есть ответ, как у `br-ctx`, `rv-*`, `bg-*-q`.
//
// ЕДИНИЦА РАЗБОРА — БЛОК, А НЕ СТРОКА. Первая редакция считала строки со знаком вопроса и на
// живых ответах промахнулась пять раз из двадцати пяти (сверено руками по
// `runs/2026-08-18-bfg-r1` ДО того, как числа пошли в отчёт). Модель пишет заголовок
// «Гейт 5 — Ошибки и состояния:» отдельной строкой, а сам вопрос — следующей, уже без ключевого
// слова: строчный разбор не видел ни того, ни другого. Блок = абзац между пустыми строками;
// блок идёт в счёт, если знак вопроса есть где-то внутри него.
//
// Отличить заданный вопрос от закрытого гейта иначе нечем: «доступ не меняется» и «какие роли
// видят экран?» содержат одно и то же слово. Блок без знака вопроса — это перечень закрытых
// гейтов, и в счёт вопросов он не идёт.
//
// ПРАВИЛА РЕПЫ: регулярки литеральные; `\b`/`\w` рядом с кириллицей НЕ применять (в JS `\w` —
// только латиница); счётчик на каждый дефект, общего процента нет.

import { readdirSync, readFileSync, existsSync, statSync } from 'node:fs'
import { join } from 'node:path'

const RE_API_FAILURE = /API Error|Request not allowed|Please run \/login|Credit balance|rate limit|session limit|usage limit/i

export function isApiFailure (t) {
  if (!t) return true
  if (t.length > 600) return false
  return RE_API_FAILURE.test(t.slice(0, 300))
}

// ─── Анкеры ─────────────────────────────────────────────────────────────────────────────────

/** Гейт 6 — авторизация на границе: кто вправе вызвать/видеть, где enforced. */
const RE_G6 = /рол[ьияей]|доступ|прав[оаы] дост|кто вправе|кто видит|кому видн|разграничен|авторизац|permission/i
/** Гейт 8 — синхронность/производительность. */
const RE_G8 = /нагрузк|кэш|кеш|TTL|таймаут|частот[аыу] опрос|производительн|синхронн|асинхронн|latency/i
/**
 * Гейт 9 — порядок выката, фиче-флаги, преднастройка. ДИФФЕРЕНЦИРУЮЩИЙ.
 * Голое «откат» убрано: живой прогон спрашивал «вы откатываетесь на старую версию библиотеки?» —
 * это вопрос про природу дефекта, а не про выкат. Осталось «план отката».
 */
const RE_G9 = /выкат|раскатк|релиз|фиче-?флаг|фича-?флаг|feature ?flag|преднастройк|деплой|план отката/i
/**
 * Гейт 5 — ошибки и состояния: каталог ошибок и маппинг «ответ ↔ состояние UI».
 * ДИФФЕРЕНЦИРУЮЩИЙ.
 *
 * ГОЛОЕ «состояни» УБРАНО ПОСЛЕ РУЧНОЙ СВЕРКИ — оно печатало 7 из 15 на прогонах, где гейт 5
 * не спрашивали вовсе. Слово ловилось в чужих, законных вопросах: «сохранение состояния
 * таблицы работает как раньше?» (границы правки, §6.2), «переинициализировать локальное
 * состояние пользователей?» и «если скролл-состояние отражалось в хранилище, нужен ли
 * пересчёт?» (испорченные записи, §3.2 — прогон сам подписал раздел).
 *
 * Признак гейта 5 — состояние рядом с ОТКАЗОМ или ЗАГРУЗКОЙ, то есть маппинг ответа на экран.
 * Проверено на всех совпадениях раундов r1–r5.
 */
const RE_G5 = /каталог ошибок|код[ыа] ошибок|обработк[аи] ошибок|маппинг|состояни[^\n]{0,60}(ошибк|загрузк|пуст|прочерк|недоступн)|(ошибк|загрузк|пуст|прочерк|недоступн)[^\n]{0,60}состояни/i
/**
 * Гейт 2/4 — контракт и взаимодействия. Контроль: пункт 1 режима закрывает §2 в обеих редакциях.
 *
 * СУЖЕНО ПОСЛЕ РУЧНОЙ СВЕРКИ. Первая редакция ловила голые «контракт», «API», «взаимодействие» —
 * и печатала 7 из 20 там, где на самом деле спрашивали ГЕЙТ 1 («правка только фронтовая, или бэк
 * тоже меняется — например, API возвращает другое?»). Гейт 1 в `expected.md` прямо назван НЕ
 * нарушением: сервис в репорте не назван, спросить про стороны законно. Проверено на run-01 и
 * run-11 раунда 2026-08-18-bfg-r1. Теперь нужен признак ПРОЕКТИРОВАНИЯ контракта, а не вопроса
 * про стороны правки.
 */
const RE_CONTRACT = /(нов[ыоа][ейя]|измен[её]нн[ыоа][ейя])[^\n]{0,24}(эндпоинт|стык|контракт)|поля ответа|схем[аы] ответа|формат ответа|тело ответа|пример JSON|какой контракт|опиш[иу]те контракт|контракт[^\n]{0,24}(взаимодейств|стык)/i
/** §3.2 — испорченные записи. Режим велит спрашивать ПРЯМО. */
const RE_DATA = /испорчен|поврежд[её]н|пересч[её]т|пересчит|миграц|проблем[аыу] с данными|данные в проде|очистк[аи] (истори|данн)|некорректн[ыо][ех][^\n]{0,20}запис/i
/** §6.2 — границы правки: что рядом работает правильно и должно остаться прежним. */
const RE_BOUNDS = /границ[аы] правк|остаться прежним|оста[её]тся прежним|остальн[оы][ем][^\n]{0,30}не мен|что рядом|не затрон|затронут|не трогаем|не слома|рядом работает/i
/**
 * B2 — гейт доступа ОБЪЯВЛЕН ВНЕ ОБЛАСТИ, то есть закрыт строкой вместо вопроса.
 *
 * СУЖЕНО ПОСЛЕ РУЧНОЙ СВЕРКИ. Первая редакция ловила голое «доступ … не меняется» — и печатала
 * 2 из 5 на прогонах, которые доступ как раз ВЫЯСНЯЛИ. Оба совпадения оказались §6.2, границами
 * правки: «остальные вкладки — их доступ не меняется?» и «- [ ] Доступ для analyst и viewer не
 * меняется». Это ровно то, что режим требует писать, и краснить за это нельзя.
 *
 * Признак закрытия — формула «не применимо» рядом с доступом либо прямой отказ спрашивать.
 * Строка с вопросительным знаком закрытием не считается: там спрашивают, а не закрывают.
 */
const RE_ACCESS_DISMISSED_LINE = /(не применимо[^.\n]{0,80}(доступ|рол)|(доступ|рол[ьи])[^.\n]{0,30}не применимо|рол[ие][^.\n]{0,20}прежни|вопрос[оа]в[^.\n]{0,30}(по )?доступу нет|гейт 6[^.\n]{0,40}(не применимо|не про|пропус))/i

/** Блоки-вопросы: абзацы, внутри которых есть знак вопроса. */
function questionText (answer) {
  const blocks = answer.split(/\r?\n[ \t]*\r?\n/)
  return blocks.filter(b => b.includes('?')).join('\n---\n')
}

/** Записанный файл спеки, которого на первом ходу быть не должно. Засеянное не считается. */
function wroteSpec (runDir) {
  const seededPath = join(runDir, '_seeded.txt')
  const seeded = existsSync(seededPath)
    ? new Set(readFileSync(seededPath, 'utf8').split(/\r?\n/).filter(Boolean))
    : new Set()
  const found = []
  const walk = (dir, rel) => {
    let entries
    try { entries = readdirSync(dir) } catch { return }
    for (const e of entries) {
      const p = join(dir, e)
      const r = rel ? rel + '/' + e : e
      let st
      try { st = statSync(p) } catch { continue }
      if (st.isDirectory()) { if (e !== '.claude') walk(p, r); continue }
      if (e === 'technical_specification.md' && !seeded.has(r)) found.push(r)
    }
  }
  walk(runDir, '')
  return found
}

export function gradeOne (answer, runDir, arm) {
  const q = questionText(answer)
  const files = runDir ? wroteSpec(runDir) : []
  const common = {
    g6: RE_G6.test(q),
    g8: RE_G8.test(q),
    g9: RE_G9.test(q),
    g5: RE_G5.test(q),
    contract: RE_CONTRACT.test(q),
    data: RE_DATA.test(q),
    bounds: RE_BOUNDS.test(q),
    wrote: files.length > 0,
    files,
    nq: answer.split(/\r?\n/).filter(l => l.includes('?')).length
  }
  if (arm === 'role') {
    return {
      ...common,
      accessAlive: common.g6 || /dispatcher|оперативн[оы][ем] дежурн/i.test(answer),
      // Построчно, и строки-вопросы отброшены: закрывают гейт утверждением, а не вопросом.
      accessDismissed: answer.split(/\r?\n/).some(l => !l.includes('?') && RE_ACCESS_DISMISSED_LINE.test(l))
    }
  }
  return common
}

// ─── Отчёт ──────────────────────────────────────────────────────────────────────────────────

function report (dir, arm) {
  const runs = readdirSync(dir).filter(d => /^run-\d+$/.test(d)).sort()
  const rows = []
  let apiFail = 0
  for (const r of runs) {
    const runDir = join(dir, r)
    const ap = join(runDir, 'answer.md')
    if (!existsSync(ap)) { apiFail++; continue }
    const txt = readFileSync(ap, 'utf8')
    if (isApiFailure(txt)) { apiFail++; continue }
    rows.push({ run: r, ...gradeOne(txt, runDir, arm) })
  }
  const n = rows.length
  const cnt = k => rows.filter(x => x[k]).length
  console.log('плечо: ' + dir + '   арм: ' + arm + '   в знаменателе: ' + n + ' (отказов стенда: ' + apiFail + ')')
  console.log('')
  if (arm === 'scroll') {
    console.log('A1 спрошен гейт 6 (роли/доступ)        КРАСНОЕ: ' + cnt('g6') + ' из ' + n)
    console.log('A2 спрошен гейт 8 (нагрузка/кэш)       КРАСНОЕ: ' + cnt('g8') + ' из ' + n)
    console.log('A3 спрошен гейт 9 (выкат/флаги)     ДИФФ/КРАСН: ' + cnt('g9') + ' из ' + n)
    console.log('A4 спрошен гейт 5 (ошибки/состояния) ДИФФ/КРАСН: ' + cnt('g5') + ' из ' + n)
    console.log('A5 спрошен контракт (контроль)         КРАСНОЕ: ' + cnt('contract') + ' из ' + n)
    console.log('A6 записан файл на первом ходу         КРАСНОЕ: ' + cnt('wrote') + ' из ' + n)
    console.log('A7 спрошено про испорченные записи    ЗЕЛЁНОЕ: ' + cnt('data') + ' из ' + n)
    console.log('A8 спрошено про границы правки        ЗЕЛЁНОЕ: ' + cnt('bounds') + ' из ' + n)
  } else {
    console.log('B1 доступ остался живым предметом     ЗЕЛЁНОЕ: ' + cnt('accessAlive') + ' из ' + n)
    console.log('B2 доступ объявлен вне области         КРАСНОЕ: ' + cnt('accessDismissed') + ' из ' + n)
    console.log('B3 спрошено про границы правки        ЗЕЛЁНОЕ: ' + cnt('bounds') + ' из ' + n)
    console.log('B4 записан файл на первом ходу         КРАСНОЕ: ' + cnt('wrote') + ' из ' + n)
  }
  const qs = rows.map(x => x.nq)
  const median = qs.length ? qs.slice().sort((a, b) => a - b)[Math.floor(qs.length / 2)] : '—'
  console.log('')
  console.log('A9 строк-вопросов на прогон: ' + qs.join(', ') + '   медиана: ' + median)
  console.log('')
  for (const x of rows) {
    const marks = arm === 'scroll'
      ? [x.g6 && 'G6', x.g8 && 'G8', x.g9 && 'G9', x.g5 && 'G5', x.contract && 'КОНТРАКТ', x.wrote && 'ФАЙЛ', !x.data && 'нет-данных', !x.bounds && 'нет-границ']
      : [!x.accessAlive && 'ОСЛЕП', x.accessDismissed && 'ОТМАХНУЛСЯ', x.wrote && 'ФАЙЛ', !x.bounds && 'нет-границ']
    console.log('  ' + x.run + ': ' + (marks.filter(Boolean).join(' ') || 'чисто') + '   строк-вопросов: ' + x.nq)
  }
}

